  var d = Duration(days: 1, hours: 2, minutes: 3, seconds: 4, milliseconds: 5, microseconds: 6);
  print(d);
  print(d.inDays);
  print(d.inHours);
  print(d.inMinutes);
  print(d.inSeconds);
  print(d.inMilliseconds);
  print(d.inMicroseconds);
  print(Duration.zero);
  print(Duration.zero.inMicroseconds);
  print(Duration());
