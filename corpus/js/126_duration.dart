  print(a - b);
  print(b - a);
  print(a * 2);
  print(a * 0.5);
  print(a * 1.5);
  print(a ~/ 2);
  print(a ~/ 7);
  print(a ~/ -2);
  print(-a);
  print(-a + a);
  print(a * 0);
  print(a * -1);
  print(a > b);
  print(a < b);
  print(a >= a);
  print(a <= b);
  print(a.compareTo(b));
  print(b.compareTo(a));
  print(a.compareTo(Duration(minutes: 90)));
  print(a.isNegative);
  print((-a).isNegative);
  print((-a).abs());
  print((-a).abs() == a);
  print(Duration.zero.isNegative);
  print(Duration(seconds: -90));
