// Conversões num: toInt, truncate/floor/ceil/round em negativos e .5, clamp, num genérico, int em double, roundToDouble.
T maior<T extends num>(T a, T b) => a > b ? a : b;
num soma(num a, num b) => a + b;
String fixo(double d) => d.toStringAsFixed(2);

void main() {
  print(3.7.toInt());
  print((-3.7).toInt());
  print(0.9.toInt());
  print((-0.9).toInt());
  print(2.5.truncate());
  print((-2.5).truncate());
  print(2.5.floor());
  print((-2.5).floor());
  print(2.5.ceil());
  print((-2.5).ceil());
  print(2.5.round());
  print(3.5.round());
  print((-2.5).round());
  print((-3.5).round());
  print(2.4999.round());
  print(0.5.round());
  print((-0.5).round());
  print(1.49.round());
  print(1e10.toInt());
  print(123.999.floor());
  print(2.5.roundToDouble().toStringAsFixed(1));
  print((-2.5).roundToDouble().toStringAsFixed(1));
  print(2.4.roundToDouble().toStringAsFixed(1));
  print(2.4.ceilToDouble().toStringAsFixed(1));
  print(2.6.floorToDouble().toStringAsFixed(1));
  print((-2.6).truncateToDouble().toStringAsFixed(1));
  print(1.5.clamp(2, 3).toStringAsFixed(1));
  print(2.5.clamp(2, 3));
  print(5.5.clamp(2.5, 3.5));
  print(5.clamp(2.5, 3.5));
  print(1.clamp(2.5, 3.5));
  print(3.clamp(2.5, 3.5));
  print((-1.5).clamp(-1, 1));
  print(maior(3, 5));
  print(maior(2.5, 1.5));
  print(maior<num>(2, 1.5));
  print(soma(1, 2));
  print(soma(1, 2.5));
  print(soma(1.5, 2.5).toStringAsFixed(1));
  print(soma(1, 2) is int);
  print(fixo(3));
  print(fixo(7 / 2));
  print(fixo(0.005));
  print(fixo(1e-10));
  double d = 5;
  print(d.toStringAsFixed(1));
  print(d / 2);
  print(d.toInt());
  print(d.toInt().isEven);
  num n = 7;
  print(n.toDouble().toStringAsFixed(1));
  print(n.toInt());
  print(n / 2);
  n = 7.5;
  print(n.toInt());
  print(n.round());
  print(n.abs());
  print(n.isNegative);
  print(n.compareTo(8));
  print(n < 8);
  print(n.floor().isOdd);
  print((n * 2).toInt());
  print(int.parse('3').toDouble().toStringAsFixed(1));
  print(3.7.toInt().toDouble().toStringAsFixed(1));
  print(1e-3.toStringAsFixed(3));
  print(1e-3 == 0.001);
  print(0.1.toStringAsFixed(20));
  print(2.675.toStringAsFixed(2));
  print(1.45.toStringAsFixed(1));
  print(1.55.toStringAsFixed(1));
  print(3.7.toInt() + 3.7.ceil());
  print((3.7 + 0.3).toInt());
  print(6.0.toInt() + 1);
  print((7 / 2).floor());
  print((7 / 2).ceil());
  print((-7 / 2).round());
  print((-7 / 2).truncate());
  var lista = [1.5, 2.5, 3.5];
  print(lista.map((e) => e.round()).toList());
  print(lista.map((e) => e.floor()).toList());
  print(lista.map((e) => e.ceil()).toList());
  print(lista.map((e) => e.truncate()).toList());
  print([-1.5, -2.5, -3.5].map((e) => e.round()).toList());
  print(0.49999999999999994.round());
  print(1e15.toInt() + 1);
  print(4503599627370496.5.toStringAsFixed(1));
  print(9.99.toStringAsFixed(1));
  print(9.95.toStringAsFixed(1));
  print(0.05.toStringAsFixed(1));
  print(0.15.toStringAsFixed(1));
  print(0.25.toStringAsFixed(1));
  print(0.35.toStringAsFixed(1));
  print(1234.5678.toStringAsFixed(2));
  print(1234.5678.toStringAsPrecision(6));
  print(1234.5678.toStringAsPrecision(1));
  print((-1234.5678).toStringAsFixed(1));
  print(0.5.toInt());
  print(1.9999999.toInt());
  print(7.clamp(1, 5).isOdd);
  print(2.7.round().isOdd);
}
