// Operadores de bits com operandos não negativos e resultados < 2^31; toRadixString e bitLength.
void main() {
  print(12 & 10);
  print(12 | 10);
  print(12 ^ 10);
  print(1 << 4);
  print(256 >> 4);
  print(256 >>> 4);
  print(255 & 0x0F);
  print(0xF0 | 0x0F);
  print(0xFF ^ 0x0F);
  print(1 << 30);
  print((1 << 30) - 1);
  print(0x7FFFFFFF);
  print(0x7FFFFFFF >> 1);
  print(0x7FFFFFFF & 0xFFFF);
  print(0x7FFFFFFF >>> 31);
  print(1 << 0);
  print(5 >> 0);
  print(5 >> 10);
  print(0 << 5);
  print(0 & 12345);
  print(0 | 12345);
  print(12345 ^ 12345);
  print(12345 ^ 0);
  print(3 & 5 | 2);
  print(3 | 5 & 2);
  print(1 + 2 << 1);
  print(1 << 1 + 2);
  print(6 & 3 == 2);
  print((6 & 3) == 2);
  print(255.toRadixString(2));
  print(255.toRadixString(16));
  print(255.toRadixString(8));
  print(255.toRadixString(36));
  print(0.toRadixString(2));
  print(1023.toRadixString(2));
  print(0xABCDEF.toRadixString(16));
  print(0xABCDEF.toRadixString(16).toUpperCase());
  print(0.bitLength);
  print(1.bitLength);
  print(2.bitLength);
  print(255.bitLength);
  print(256.bitLength);
  print(0x7FFFFFFF.bitLength);
  print((1 << 30).bitLength);
  var flags = 0;
  flags |= 1 << 0;
  flags |= 1 << 3;
  print(flags);
  print(flags & (1 << 3) != 0);
  print(flags & (1 << 1) != 0);
  flags &= 0xFE;
  print(flags);
  flags ^= 1 << 3;
  print(flags);
  var x = 5;
  x <<= 2;
  print(x);
  x >>= 1;
  print(x);
  x >>>= 1;
  print(x);
  print(int.parse('1010', radix: 2) << 2);
  print(int.parse('ff', radix: 16) & 0x0F);
  var bits = <int>[];
  for (var i = 7; i >= 0; i--) {
    bits.add((0xA5 >> i) & 1);
  }
  print(bits.join());
  print(0xA5.toRadixString(2).padLeft(8, '0'));
  var pop = 0;
  var v = 0xA5;
  while (v != 0) {
    pop += v & 1;
    v >>= 1;
  }
  print(pop);
  print(0x12345678 & 0xFF00FF);
  print(0x12345678 >> 8 & 0xFF);
  print((0x12 << 8) | 0x34);
  print(0x0F0F ^ 0xFFFF);
  print(1 << 20 | 1 << 10 | 1);
  print((1 << 31) - 1 == 0x7FFFFFFF);
  print(1000000 & 999999);
  print(1000000 | 999999);
  print(1000000 ^ 999999);
  print(0x40000000 >> 30);
  print(0x40000000 >>> 29);
  print(7 << 28);
  print((7 << 28) >> 28);
  print(255 & ~15 & 0xFF);
  print(0x3 & 0x5);
}
