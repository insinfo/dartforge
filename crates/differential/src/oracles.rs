//! The three executors: `dart run` (semantics), `dartdevc` + Node (contract) and DartForge.
//!
//! There are **two oracle SDKs** (`docs/VERSOES-LINGUAGEM.md` §5): 3.6.2, the
//! floor, which is the oracle of `corpus/js`, and 3.13.4, the one for the new
//! features (`corpus/moderno`). Each program goes to the smallest SDK whose
//! version covers its `// requer-dart:`; the DDC column uses **that** SDK's
//! `dartdevc` linked to **its** `dart_sdk.js`. DartForge still links the 3.6.2
//! `dart_sdk.js` (D1) and receives a `--language-version` equal to the
//! required version.
//!
//! Some texts here are compared or cached (the rejection line of negative
//! programs, the cache file names and labels, the output directory names
//! under `target/differential/`) or match the output of other tools; changing
//! them invalidates the oracle cache, so they are marked where they appear.

use std::path::{Path, PathBuf};
use std::time::Duration;

use dartforge_frontend::LanguageVersion;

use crate::corpus::Program;
use crate::process::{Output, run, run_with_env, run_with_path};

/// A Dart SDK used as an oracle.
#[derive(Debug, Clone)]
pub struct OracleSdk {
    /// The SDK's current language version (3.6, 3.13).
    pub version: LanguageVersion,
    /// The full version, from the `version` file (`3.13.4`).
    pub name: String,
    /// SDK root (the folder with `bin/` and `lib/`).
    pub root: PathBuf,
    /// The `dart_sdk.js` generated by this SDK's `dartdevc`.
    pub dart_sdk_js: PathBuf,
    /// The floor SDK (3.6.2): its cache labels do not carry the version, so
    /// that the cache CI already has stays valid.
    pub primary: bool,
}

impl OracleSdk {
    /// Reads the version from `<root>/version`; `None` if it is not an SDK.
    pub fn detect(root: PathBuf, dart_sdk_js: PathBuf, primary: bool) -> Option<OracleSdk> {
        let name = std::fs::read_to_string(root.join("version")).ok()?.trim().to_string();
        let mut parts = name.split('.');
        let version = LanguageVersion::new(parts.next()?.parse().ok()?, parts.next()?.parse().ok()?);
        Some(OracleSdk { version, name, root, dart_sdk_js, primary })
    }

    /// The SDK's `dart` executable; `dart` from `PATH` if the SDK lacks it.
    pub fn dart(&self) -> String {
        let exe = self.root.join("bin").join(if cfg!(windows) { "dart.exe" } else { "dart" });
        if exe.is_file() { exe.to_string_lossy().into_owned() } else { "dart".to_string() }
    }

    fn dartdevc_snapshot(&self) -> PathBuf {
        self.root.join("bin/snapshots/dartdevc.dart.snapshot")
    }

    /// An executor's label in the cache: the floor's does not change
    /// (`dart-ea`), the others' carry the version (`dart-ea-3.13.4`).
    fn label(&self, executor: &str) -> String {
        if self.primary { executor.to_string() } else { format!("{executor}-{}", self.name) }
    }
}

/// Where the tools are. Built once per harness run.
#[derive(Debug, Clone)]
pub struct Environment {
    /// Repository root (parent of `crates/`).
    pub root: PathBuf,
    /// Root of the floor Dart SDK (`C:/tools/dartsdk-3.6.2`); `DARTFORGE_DART_SDK` overrides.
    pub sdk: PathBuf,
    /// `runtime/ddc/dart_sdk.js` (the floor's, which is also the one DartForge links).
    pub dart_sdk_js: PathBuf,
    /// The oracle SDKs, from smallest to largest: the floor and, if
    /// configured, 3.13 (`DARTFORGE_DART_SDK_3_13`, default
    /// `E:/DartSDKs/3.13.4/dart-sdk`).
    pub sdks: Vec<OracleSdk>,
    /// The `dartforge` binary when already built (`DARTFORGE_BIN` overrides).
    pub dartforge_bin: Option<PathBuf>,
    /// `target/differential/`.
    pub work_dir: PathBuf,
    /// Use the oracle cache keyed by content hash.
    pub use_cache: bool,
    /// Limit per process.
    pub timeout: Duration,
    /// Limit only for RUNNING the native binary.
    ///
    /// Separate from `timeout` because the two measure different things: the
    /// `dart run` oracle can take seconds just to start, while a corpus
    /// program running natively finishes in milliseconds — if it takes long,
    /// it is stuck in a loop. And an infinite loop in native code does not
    /// only cost time: while it spins, it allocates, and several in parallel
    /// take the machine's memory. Short by default; `--exec-limit` adjusts it.
    pub native_timeout: Duration,
    /// Directories prepended to `dartforge`'s `PATH` (the `LLVM-C.dll`; see `scripts/env.ps1`).
    pub extra_path: Vec<PathBuf>,
    /// `--gc-stress`: the native executable runs with `DARTFORGE_GC_STRESS=1`.
    pub gc_stress: bool,
    /// `--optimize`: the native executable is the production one
    /// (`aot --optimize`: a single executable, LTO and method-table pruning,
    /// docs/NATIVO-PODA-DE-TABELAS.md).
    pub optimize: bool,
}

impl Environment {
    /// Detects everything from the crate directory; generates `dart_sdk.js` if missing.
    pub fn detect() -> Environment {
        // With `target/` shared between worktrees, the embedded
        // `CARGO_MANIFEST_DIR` points to the tree that built this binary last,
        // not to the tree of whoever is running it. The root is the current
        // directory when it has the corpus (which is what `cargo run` does),
        // otherwise the embedded path.
        let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
        let root = if cwd.join("corpus/js").is_dir() {
            cwd
        } else {
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").canonicalize().unwrap_or_else(|_| PathBuf::from("."))
        };
        let root = strip_verbatim_prefix(root);
        let sdk = std::env::var("DARTFORGE_DART_SDK").map(PathBuf::from).unwrap_or_else(|_| PathBuf::from("E:/DartSDKs/3.6.2"));
        let dart_sdk_js = root.join("runtime/ddc/dart_sdk.js");
        generate_dart_sdk_js(&root, &sdk, &dart_sdk_js);
        let mut sdks: Vec<OracleSdk> = OracleSdk::detect(sdk.clone(), dart_sdk_js.clone(), true).into_iter().collect();
        // The second oracle: the SDK of the new features. Without it the
        // programs that require it come out as a harness failure, with the
        // message saying what to configure — never compared against the wrong
        // SDK.
        let sdk_313 = std::env::var("DARTFORGE_DART_SDK_3_13")
            .map(PathBuf::from)
            .unwrap_or_else(|_| PathBuf::from("E:/DartSDKs/3.13.4/dart-sdk"));
        if let Some(mut s) = OracleSdk::detect(sdk_313.clone(), PathBuf::new(), false) {
            s.dart_sdk_js = root.join("runtime/ddc").join(&s.name).join("dart_sdk.js");
            generate_dart_sdk_js(&root, &sdk_313, &s.dart_sdk_js);
            sdks.push(s);
        }
        sdks.sort_by_key(|s| s.version);
        let target = std::env::var("CARGO_TARGET_DIR").map(PathBuf::from).unwrap_or_else(|_| root.join("target"));
        let dartforge_bin = std::env::var("DARTFORGE_BIN").ok().map(PathBuf::from).or_else(|| {
            let exe = if cfg!(windows) { "dartforge.exe" } else { "dartforge" };
            // For the same reason, the right `dartforge` is the one next to
            // this executable (same `target/<profile>/`), before any other.
            let beside = std::env::current_exe().ok().and_then(|e| e.parent().map(|d| d.join(exe)));
            let mut candidates: Vec<PathBuf> = beside.into_iter().collect();
            candidates.push(target.join("release").join(exe));
            candidates.push(target.join("debug").join(exe));
            candidates.into_iter().find(|p| p.is_file())
        });
        let mut extra_path = Vec::new();
        for prefix in [std::env::var("LLVM_SYS_221_PREFIX").ok(), std::env::var("DARTFORGE_LLVM_DIR").ok(), Some(r"E:\llvm\clang+llvm-22.1.8-x86_64-pc-windows-msvc".to_string())].into_iter().flatten() {
            let bin = PathBuf::from(prefix).join("bin");
            if bin.join("LLVM-C.dll").is_file() {
                extra_path.push(bin);
                break;
            }
        }
        Environment {
            extra_path,
            // Holds the oracle cache: renaming it starts a new cache.
            work_dir: target.join("differential"),
            root,
            sdk,
            dart_sdk_js,
            sdks,
            dartforge_bin,
            use_cache: true,
            timeout: Duration::from_secs(120),
            native_timeout: Duration::from_secs(5),
            gc_stress: false,
            optimize: false,
        }
    }

    /// A program's oracle: the smallest SDK whose version covers its
    /// `// requer-dart:` (and the `// @dart=` marker, which the SDK must also
    /// accept). `Err` says what is left to configure.
    pub fn oracle(&self, program: &Program) -> Result<&OracleSdk, String> {
        let required = program.marker.map_or(program.requires, |m| m.max(program.requires));
        self.sdks.iter().find(|s| s.version >= required).ok_or_else(|| {
            format!(
                "no oracle SDK with version ≥ {required} (configured: {}); set DARTFORGE_DART_SDK_3_13",
                self.sdks.iter().map(|s| s.name.as_str()).collect::<Vec<_>>().join(", ")
            )
        })
    }

    /// Output directory of a program for an executor (`ddc`, `forge`, `contract`).
    /// The executor names are directories on disk.
    pub fn output_dir(&self, executor: &str, program: &Program) -> PathBuf {
        self.work_dir.join(executor).join(&program.name)
    }
}

/// Generates `destination` (the `dart_sdk.js` of `sdk`) with
/// `scripts/generate-dart-sdk.ps1` if it does not exist yet.
fn generate_dart_sdk_js(root: &Path, sdk: &Path, destination: &Path) {
    if destination.is_file() || !sdk.join("version").is_file() {
        return;
    }
    eprintln!("{} missing; generating it with scripts/generate-dart-sdk.ps1…", destination.display());
    let args = vec![
        root.join("scripts/generate-dart-sdk.ps1").to_string_lossy().into_owned(),
        "-Sdk".into(),
        sdk.to_string_lossy().into_owned(),
        "-Output".into(),
        destination.parent().unwrap_or(root).to_string_lossy().into_owned(),
    ];
    let s = run("pwsh", &args, root, Duration::from_secs(300));
    if s.code != 0 {
        eprintln!("failed: {}", s.stderr);
    }
}

/// On Windows, `canonicalize` returns `\\?\D:\…`, which confuses external tools.
fn strip_verbatim_prefix(p: PathBuf) -> PathBuf {
    let s = p.to_string_lossy();
    match s.strip_prefix(r"\\?\") {
        Some(r) => PathBuf::from(r),
        None => p,
    }
}

// ---------------------------------------------------------------- cache

fn hash_fnv(data: &[u8]) -> u64 {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in data {
        h ^= *b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    h
}

fn cache_key(program: &Program) -> String {
    format!("{:016x}", hash_fnv(&program.contents()))
}

fn cache_read(env: &Environment, executor: &str, key: &str) -> Option<Output> {
    if !env.use_cache {
        return None;
    }
    let text = std::fs::read_to_string(env.work_dir.join("cache").join(format!("{executor}-{key}.txt"))).ok()?;
    // Format: `code\nlen_stdout\n<stdout><stderr>`.
    let (code, rest) = text.split_once('\n')?;
    let (len, body) = rest.split_once('\n')?;
    let len: usize = len.parse().ok()?;
    if !body.is_char_boundary(len) {
        return None;
    }
    Some(Output { stdout: body[..len].to_string(), stderr: body[len..].to_string(), code: code.parse().ok()? })
}

fn cache_write(env: &Environment, executor: &str, key: &str, s: &Output) {
    if !env.use_cache || s.code < 0 {
        return; // harness failures (missing tool, timeout) do not enter the cache
    }
    let dir = env.work_dir.join("cache");
    let _ = std::fs::create_dir_all(&dir);
    let text = format!("{}\n{}\n{}{}", s.code, s.stdout.len(), s.stdout, s.stderr);
    let _ = std::fs::write(dir.join(format!("{executor}-{key}.txt")), text);
}

// ---------------------------------------------------------------- dart run

/// `--enable-experiment=a,b` from the header, if any.
fn experiments_arg(program: &Program) -> Option<String> {
    (!program.experiments.is_empty()).then(|| format!("--enable-experiment={}", program.experiments.join(",")))
}

/// Semantics oracle: `dart run --enable-asserts file` in the file's
/// directory, with the `dart` of the program's oracle SDK
/// ([`Environment::oracle`]). Asserts are enabled because DDC (and
/// DartForge's development mode) enables them.
pub fn dart_oracle(env: &Environment, program: &Program) -> Output {
    let sdk = match env.oracle(program) {
        Ok(s) => s,
        Err(e) => return Output::error(e),
    };
    let label = sdk.label("dart-ea");
    let key = cache_key(program);
    let s = match cache_read(env, &label, &key) {
        Some(s) => s,
        None => {
            let name = program.entry.file_name().unwrap().to_string_lossy().into_owned();
            let mut args: Vec<String> = vec!["run".into(), "--enable-asserts".into()];
            args.extend(experiments_arg(program));
            args.push(name);
            let mut s = run(&sdk.dart(), &args, program.dir(), env.timeout);
            // The 3.13 VM on Windows writes `print` with `\r\n` (3.6.2 and
            // Node write `\n`): the console's line ending is not the
            // program's semantics.
            if !sdk.primary {
                s.stdout = s.stdout.replace("\r\n", "\n");
            }
            cache_write(env, &label, &key, &s);
            s
        }
    };
    if program.compile_error && s.code == 254 {
        return rejection(cfe_error_line(&s));
    }
    s
}

// ---------------------------------------------------------------- negative programs

/// The comparable output of an executor that **rejected** a negative program
/// (`// erro-de-compilacao`): the line of the first error it reported. Code 0,
/// so that the report does not mistake an expected rejection for a broken
/// oracle; what is compared is the text.
///
/// The text is cached (DDC's rejection goes into the oracle cache) and
/// compared between executors: changing it requires a new oracle cache.
pub fn rejection(line: Option<usize>) -> Output {
    let stdout = match line {
        Some(l) => format!("compile error at line {l}
"),
        None => "compile error (line not identified)
".to_string(),
    };
    Output { stdout, stderr: String::new(), code: 0 }
}

/// The line of the first `file.dart:L:C: Error:` that the CFE (VM or
/// `dartdevc`) printed, on stdout or stderr.
pub fn cfe_error_line(s: &Output) -> Option<usize> {
    s.stderr.lines().chain(s.stdout.lines()).find_map(|l| {
        let (before, _) = l.split_once(": Error:")?;
        let pos = before.rfind(".dart:")?;
        let mut fields = before[pos + ".dart:".len()..].split(':');
        let line: usize = fields.next()?.parse().ok()?;
        fields.next()?.parse::<usize>().ok()?;
        Some(line)
    })
}

/// The line of DartForge's first error: the diagnostics end in
/// `at bytes S..E` (offset in the source); the line is counted in the entry.
pub fn forge_error_line(text: &str, source: &str) -> Option<usize> {
    // Only the error lines: the type warnings (`warning: … at bytes …`) also
    // carry an offset, and may belong to another unit. The `error` prefix is
    // the dartforge CLI's diagnostic text.
    let start: Option<usize> = text.lines().filter(|l| l.trim_start().starts_with("error")).find_map(|l| {
        let (_, rest) = l.rsplit_once(" at bytes ")?;
        rest.split("..").next()?.trim().parse().ok()
    });
    if let Some(start) = start {
        let start = start.min(source.len());
        return Some(source.as_bytes()[..start].iter().filter(|b| **b == b'\n').count() + 1);
    }
    // The language errors of the native lowering: `message (file.dart:L:C)`.
    text.lines().find_map(|l| {
        let (_, pos) = l.trim_end().strip_suffix(')')?.rsplit_once(" (")?;
        let (_, lc) = pos.rsplit_once(".dart:")?;
        let mut fields = lc.split(':');
        let line: usize = fields.next()?.parse().ok()?;
        fields.next()?.parse::<usize>().ok()?;
        Some(line)
    })
}

/// For a negative program: DartForge rejected it (code ≠ 0 at compile time)
/// → [`rejection`] with its line; it accepted it → the output as is, which
/// does not match the VM's rejection.
fn normalize_forge_rejection(program: &Program, compilation: &Output) -> Option<Output> {
    if !program.compile_error || compilation.code == 0 {
        return None;
    }
    let source = std::fs::read_to_string(&program.entry).unwrap_or_default();
    let text = format!("{}\n{}", compilation.stderr, compilation.stdout);
    Some(rejection(forge_error_line(&text, &source)))
}

// ---------------------------------------------------------------- dartdevc + node

/// Compiles the program with the `dartdevc` (`--modules=es6`) of its oracle
/// SDK into `dir/<name>.js` and returns the JS already pointing to that SDK's
/// `dart_sdk.js`. `Err` carries the compiler's output.
pub fn compile_ddc(env: &Environment, program: &Program, dir: &Path) -> Result<String, Output> {
    let sdk = env.oracle(program).map_err(Output::error)?;
    let _ = std::fs::create_dir_all(dir);
    let js = dir.join(format!("{}.js", program.name));
    // `dartdevc` already follows relative imports; only the entry is passed.
    // The cwd is the program's directory so that the module name is the file
    // name.
    let mut args = vec![
        sdk.dartdevc_snapshot().to_string_lossy().into_owned(),
        "--modules=es6".into(),
        "-o".into(),
        js.to_string_lossy().into_owned(),
    ];
    args.extend(experiments_arg(program));
    // Programs with `package:` bring their own `.dart_tool/package_config.json`
    // (`dart run` finds it by itself; `dartdevc` needs `--packages`).
    let packages = program.dir().join(".dart_tool/package_config.json");
    if packages.is_file() {
        args.push(format!("--packages={}", packages.to_string_lossy()));
    }
    args.push(program.entry.file_name().unwrap().to_string_lossy().into_owned());
    let s = run(&sdk.dart(), &args, program.dir(), env.timeout);
    if s.code != 0 {
        return Err(s);
    }
    let text = std::fs::read_to_string(&js).map_err(|e| Output::error(format!("reading {}: {e}", js.display())))?;
    let url = file_url(&sdk.dart_sdk_js);
    let text = text.replace("from 'dart_sdk.js'", &format!("from '{url}'"));
    std::fs::write(&js, &text).map_err(|e| Output::error(format!("writing {}: {e}", js.display())))?;
    Ok(text)
}

fn file_url(p: &Path) -> String {
    let s = p.to_string_lossy().replace('\\', "/");
    if s.starts_with('/') { format!("file://{s}") } else { format!("file:///{s}") }
}

/// Exported name of the entry library: the first entry of the
/// `export { … };` line (`export { $01_print }`, `export { hello as x__hello }`,
/// `export { main, util }`).
pub fn exported_name(js: &str) -> Option<String> {
    let line = js.lines().find(|l| l.starts_with("export {"))?;
    let inner = line.trim_start_matches("export {").trim_end_matches(';').trim_end_matches('}').trim();
    let first = inner.split(',').next()?.trim();
    let name = match first.split_once(" as ") {
        Some((_, alias)) => alias.trim(),
        None => first,
    };
    Some(name.to_string())
}

/// A `main.mjs` that runs the module's `main()` and mimics the VM on an
/// uncaught error (exit code 255).
pub fn main_mjs(module: &str, exported: &str) -> String {
    format!(
        "process.on('uncaughtException', (e) => {{\n  console.error('Unhandled exception:\\n' + e);\n  process.exit(255);\n}});\nimport {{ {exported} as m }} from './{module}.js';\nm.main();\n"
    )
}

/// Runs `node main.mjs` in `dir`.
pub fn run_node(env: &Environment, dir: &Path) -> Output {
    run("node", &["main.mjs".into()], dir, env.timeout)
}

/// Contract oracle: `dartdevc` + Node. Cached by content hash.
pub fn ddc_oracle(env: &Environment, program: &Program, dir: &Path) -> Output {
    let label = match env.oracle(program) {
        Ok(sdk) => sdk.label("ddc"),
        Err(e) => return Output::error(e),
    };
    let key = cache_key(program);
    if let Some(s) = cache_read(env, &label, &key) {
        return s;
    }
    let s = match compile_ddc(env, program, dir) {
        // Negative program: `dartdevc` rejected it, as it should.
        Err(s) if program.compile_error && s.code > 0 => rejection(cfe_error_line(&s)),
        Err(s) => s,
        Ok(js) => match exported_name(&js) {
            None => Output::error("dartdevc: `export { … }` line not found"),
            Some(exp) => {
                if std::fs::write(dir.join("main.mjs"), main_mjs(&program.name, &exp)).is_err() {
                    return Output::error("could not write main.mjs");
                }
                run_node(env, dir)
            }
        },
    };
    cache_write(env, &label, &key, &s);
    s
}

// ---------------------------------------------------------------- dartforge

/// The current version DartForge compiles the program with: that of its
/// oracle SDK (the version the VM gives a file without a marker); without an
/// oracle, the one required by the header.
pub fn program_version(env: &Environment, program: &Program) -> LanguageVersion {
    env.oracle(program).map_or_else(|_| required_version(program), |s| s.version)
}

/// `// requer-dart:` and the `// @dart=` marker, the larger of the two.
pub fn required_version(program: &Program) -> LanguageVersion {
    program.marker.map_or(program.requires, |m| m.max(program.requires))
}

/// `--language-version x.y` and, if any, `--enable-experiment=…` for DartForge.
fn language_args(env: &Environment, program: &Program) -> Vec<String> {
    let mut a = vec!["--language-version".to_string(), program_version(env, program).to_string()];
    a.extend(experiments_arg(program));
    a
}

/// DartForge: `dartforge compile-js file -o dir` and then `node dir/main.mjs`.
/// No cache: the emitter changes all the time.
pub fn dartforge(env: &Environment, program: &Program, dir: &Path) -> Output {
    let _ = std::fs::create_dir_all(dir);
    let entry = program.dartforge_entry().to_string_lossy().into_owned();
    let out_dir = dir.to_string_lossy().into_owned();
    let mut args: Vec<String> = vec!["compile-js".into(), entry, "-o".into(), out_dir];
    args.extend(language_args(env, program));
    let s = match &env.dartforge_bin {
        Some(bin) => run_with_path(
            &bin.to_string_lossy(),
            &args,

            program.dartforge_dir(),
            env.timeout,
            &env.extra_path,
        ),
        None => run_with_path(
            "cargo",
            &[vec!["run".into(), "-q".into(), "-p".into(), "dartforge-cli".into(), "--".into()], args].concat(),
            &env.root,
            Duration::from_secs(1800),
            &env.extra_path,
        ),
    };
    if let Some(r) = normalize_forge_rejection(program, &s) {
        return r;
    }
    if s.code != 0 {
        let first = s.first_stderr_line().to_string();
        let first = if first.is_empty() { s.stdout.lines().next().unwrap_or("").to_string() } else { first };
        // The `[compile-js` prefix marks a compile-time rejection (`matrix.rs`).
        return Output { stderr: format!("[compile-js code {}] {first}
{}", s.code, s.stderr), ..s };
    }
    if !dir.join("main.mjs").is_file() {
        return Output::error("[compile-js] returned 0 but did not write main.mjs");
    }
    run_node(env, dir)
}

/// DartForge Native: compiles via `dartforge_emit_native::compile` and then runs the binary.
pub fn dartforge_native(env: &Environment, program: &Program, dir: &Path) -> Output {
    let _ = std::fs::create_dir_all(dir);
    let exe_name = if cfg!(windows) { format!("{}.exe", program.name) } else { program.name.clone() };
    let exe_path = dir.join(&exe_name);

    let entry = program.entry.clone();
    let out_path = exe_path.clone();
    let version = program_version(env, program);
    let optimize = env.optimize;
    let compiled = std::thread::Builder::new()
        .stack_size(1 << 30)
        .spawn(move || {
            let options = dartforge_emit_native::CompileOptions {
                sdk: None,
                packages: None,
                timings: false,
                optimize,
                language_version: Some(version),
                experiments: Vec::new(),
                debug: false,
                generator: None,
                cpu: None,
            };
            dartforge_emit_native::compile(&entry, &out_path, &options)
        })
        .map_err(|e| format!("failed to create the compilation thread: {e}"))
        .and_then(|h| h.join().map_err(|_| "the compilation thread aborted".to_string()))
        .and_then(|r| r);

    if let (true, Err(e)) = (program.compile_error, &compiled) {
        let source = std::fs::read_to_string(&program.entry).unwrap_or_default();
        return rejection(forge_error_line(e, &source));
    }
    if let Err(e) = compiled {
        return compile_error_output(&e);
    }

    if !exe_path.is_file() {
        return Output::error("[compile-native] returned Ok but did not produce an executable");
    }

    let child_env: &[(&str, &str)] = if env.gc_stress { &[("DARTFORGE_GC_STRESS", "1")] } else { &[] };
    let s = run_with_env(&exe_path.to_string_lossy(), &[], dir, env.native_timeout, &env.extra_path, child_env);
    // The executable has already said what it had to say; 214 of them would
    // stay on disk on every pass. DARTFORGE_KEEP_EXE keeps them for debugging.
    if std::env::var_os("DARTFORGE_KEEP_EXE").is_none() {
        let _ = std::fs::remove_file(&exe_path);
    }
    s
}

/// Only the native backend's emission: the program's LLVM IR, without Clang,
/// linking or running. It is what determinism mode compares — the executable
/// is a function of the IR, of the Clang version and of the runtime `.lib`,
/// and what can vary with the workers' order is our code, which shows up
/// entirely in the IR.
///
/// Same 1 GiB stack as [`dartforge_native`]. A panic during emission becomes
/// an `Err` with its message (without the thread id, which would change from
/// run to run), to be compared like any other result.
pub fn dartforge_native_ir(program: &Program) -> Result<String, String> {
    emit_program_ir(program, false)
}

/// The IR the JIT runs: without static objects (the JIT does not have them,
/// a generation's memory is freed; docs/NATIVO-ESPACO-UNIFICADO.md §2.11), like
/// `dartforge run` (`emit_reloadable_ir`). `--jit-aot` links this same IR.
pub fn dartforge_native_ir_jit(program: &Program) -> Result<String, String> {
    emit_program_ir(program, true)
}

fn emit_program_ir(program: &Program, jit: bool) -> Result<String, String> {
    let entry = program.entry.clone();
    let version = required_version(program);
    std::thread::Builder::new()
        .stack_size(1 << 30)
        .spawn(move || {
            let options = dartforge_emit_native::CompileOptions {
                sdk: None,
                packages: None,
                timings: false,
                optimize: false,
                language_version: Some(version),
                experiments: Vec::new(),
                debug: false,
                generator: None,
                cpu: None,
            };
            if jit {
                dartforge_emit_native::emit_reloadable_ir(&entry, &options, None).map(|ir| ir.text)
            } else {
                dartforge_emit_native::emit_ir(&entry, &options).map(|ir| ir.text)
            }
        })
        .map_err(|e| format!("[emit-ir] failed to create the emission thread: {e}"))?
        .join()
        .map_err(|p| format!("[emit-ir] the thread aborted: {}", panic_message(p.as_ref())))?
        .map_err(|e| format!("[emit-ir] {e}"))
}

fn panic_message(payload: &(dyn std::any::Any + Send)) -> String {
    if let Some(s) = payload.downcast_ref::<&str>() {
        (*s).to_string()
    } else if let Some(s) = payload.downcast_ref::<String>() {
        s.clone()
    } else {
        "(panic without a message)".to_string()
    }
}

