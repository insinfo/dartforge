//! The JavaScript interop of WebAssembly modules (`dart:js_interop`,
//! docs/PLANO-WASM-MVP.md, "Desenho do interop JS"; docs/WASM-HOST-ABI-V1.md).
//!
//! As in dart2wasm, every piece of JavaScript a module runs is a *snippet*: the
//! text of a JavaScript function that the compiler writes into the companion
//! `.mjs` and that the module imports. A snippet comes from an `external`
//! function of the target's SDK with `@pragma('dartforge:js', '<code>')`
//! (`dart:_js_helper`, `dart:js_interop`'s patches) or from the lowering of an
//! interop member. The declared Dart types of its parameters and return choose
//! how each value crosses ([`Kind`]).
//!
//! In the objects, a snippet is a call to `@dfjs.<hex>` ([`Snippet::symbol`]),
//! imported from [`JS_MODULE`] under the name `s:<hex>`: the key holds the
//! signature and the code, so equal snippets of different objects are one import.
//! After the link, [`finish_module`] renames those imports to short names and
//! writes the companion with their JavaScript.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

pub use dartforge_wasm_gate::JS_MODULE;

/// The prefix of a snippet call's `CallRuntime` name (HIR) and LLVM symbol.
pub const SNIPPET_PREFIX: &str = "dfjs.";

/// The prefix of a snippet's import name in an object, before [`finish_module`].
pub const IMPORT_PREFIX: &str = "s:";

/// The runtime entry the adapter calls when a snippet throws
/// (`crates/runtime/src/js_interop.rs`): exported by every module with snippets.
pub const THROW_EXPORT: &str = "dartforge_js_throw";

/// The first line of every companion, which marks the file as generated.
pub const COMPANION_HEADER: &str = "// Generated by DartForge: the JavaScript of ";

/// The snippets of a module by import name.
pub type NamedSnippets = Vec<(String, Snippet)>;

/// How a value crosses between Dart and a snippet.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Kind {
    /// A JavaScript value (`JSValue` and the JS types, nullable or not): a handle
    /// of the adapter's table, `i32`; 0 is `null`/`undefined`. A returned handle
    /// is new and belongs to the caller.
    Value,
    /// `double`: an `f64`, the JavaScript number.
    Number,
    /// `int`: passed as the JavaScript number of its value (an `f64`);
    /// returned as an `i32` (`ToInt32`, dart2wasm's `JS<WasmI32>(…).toIntSigned()`).
    Integer,
    /// `bool`: an `i32` 0/1, as dart2wasm passes it (the JavaScript code sees a
    /// number); a returned value is converted with `ToInt32` and compared with 0.
    Boolean,
    /// `bool` as the JavaScript boolean (an interop member's argument): 0/1 at
    /// the boundary, `true`/`false` for the JavaScript code. Arguments only.
    JsBoolean,
    /// `String`/`String?`: a JavaScript string the call creates and the wrapper
    /// consumes (a handle, `i32`); returned, a handle the Dart side converts.
    Text,
    /// No value (returns only).
    Void,
}

impl Kind {
    fn code(self) -> char {
        match self {
            Kind::Value => 'r',
            Kind::Number => 'd',
            Kind::Integer => 'n',
            Kind::Boolean => 'b',
            Kind::JsBoolean => 'B',
            Kind::Text => 's',
            Kind::Void => 'v',
        }
    }

    fn from_code(c: char) -> Option<Kind> {
        Some(match c {
            'r' => Kind::Value,
            'd' => Kind::Number,
            'n' => Kind::Integer,
            'b' => Kind::Boolean,
            'B' => Kind::JsBoolean,
            's' => Kind::Text,
            'v' => Kind::Void,
            _ => return None,
        })
    }

    /// The type of a parameter at the import (LLVM IR).
    pub fn wasm_param(self) -> &'static str {
        match self {
            Kind::Value | Kind::Boolean | Kind::JsBoolean | Kind::Text => "i32",
            Kind::Number | Kind::Integer => "double",
            Kind::Void => "void",
        }
    }

    /// The type of the result at the import (LLVM IR).
    pub fn wasm_result(self) -> &'static str {
        match self {
            Kind::Value | Kind::Boolean | Kind::JsBoolean | Kind::Text | Kind::Integer => "i32",
            Kind::Number => "double",
            Kind::Void => "void",
        }
    }
}

/// A snippet: its JavaScript function and how its values cross.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Snippet {
    pub params: Vec<Kind>,
    pub ret: Kind,
    /// The text of a JavaScript function expression (`(o, p) => o[p]`).
    pub code: String,
}

impl Snippet {
    /// `rr>r`: the kinds of the parameters, `>`, the kind of the return.
    pub fn signature(&self) -> String {
        let mut s: String = self.params.iter().map(|k| k.code()).collect();
        s.push('>');
        s.push(self.ret.code());
        s
    }

    fn key(&self) -> String {
        format!("{}|{}", self.signature(), self.code)
    }

    fn from_key(key: &str) -> Option<Snippet> {
        let (signature, code) = key.split_once('|')?;
        let (params, ret) = signature.split_once('>')?;
        let params = params
            .chars()
            .map(|c| Kind::from_code(c).filter(|&k| k != Kind::Void))
            .collect::<Option<Vec<_>>>()?;
        let mut ret_chars = ret.chars();
        let ret = Kind::from_code(ret_chars.next()?)?;
        if ret_chars.next().is_some() || ret == Kind::JsBoolean {
            return None;
        }
        Some(Snippet {
            params,
            ret,
            code: code.to_string(),
        })
    }

    /// The name of the `CallRuntime` and of the LLVM function: `dfjs.<hex>`.
    pub fn symbol(&self) -> String {
        format!("{SNIPPET_PREFIX}{}", hex(self.key().as_bytes()))
    }

    /// The snippet of a [`Snippet::symbol`].
    pub fn from_symbol(symbol: &str) -> Option<Snippet> {
        let bytes = unhex(symbol.strip_prefix(SNIPPET_PREFIX)?)?;
        Self::from_key(std::str::from_utf8(&bytes).ok()?)
    }

    /// The import name in the objects: `s:<hex>`.
    pub fn import_name(&self) -> String {
        format!("{IMPORT_PREFIX}{}", hex(self.key().as_bytes()))
    }

    /// The snippet of an [`Snippet::import_name`].
    pub fn from_import_name(name: &str) -> Option<Snippet> {
        let bytes = unhex(name.strip_prefix(IMPORT_PREFIX)?)?;
        Self::from_key(std::str::from_utf8(&bytes).ok()?)
    }

    /// The LLVM declaration of the import.
    pub fn declaration(&self) -> String {
        let params: Vec<&str> = self.params.iter().map(|k| k.wasm_param()).collect();
        format!(
            "declare {} @{}({}) \"wasm-import-module\"=\"{JS_MODULE}\" \"wasm-import-name\"=\"{}\"",
            self.ret.wasm_result(),
            self.symbol(),
            params.join(", "),
            self.import_name()
        )
    }

    /// The companion's entry for import `name`, with the snippet's function in
    /// `f<index>`: the conversion of each argument, the call, the conversion of
    /// the result, and the exception, which becomes the Dart side's
    /// (`r.fail`, `_JavaScriptError`).
    fn javascript(&self, name: &str, index: usize) -> (String, String) {
        let function = format!("  const f{index} = {};\n", self.code.trim());
        let params: Vec<String> = (0..self.params.len()).map(|i| format!("a{i}")).collect();
        let args: Vec<String> = self
            .params
            .iter()
            .zip(&params)
            .map(|(k, a)| match k {
                Kind::Value => format!("r.get({a})"),
                Kind::Text => format!("r.take({a})"),
                Kind::JsBoolean => format!("{a} !== 0"),
                Kind::Number | Kind::Integer | Kind::Boolean | Kind::Void => a.clone(),
            })
            .collect();
        let call = format!("f{index}({})", args.join(", "));
        let body = match self.ret {
            Kind::Value | Kind::Text => format!("return r.ref({call});"),
            Kind::Number | Kind::Boolean | Kind::JsBoolean | Kind::Integer => {
                format!("return {call};")
            }
            Kind::Void => format!("{call};"),
        };
        let entry = format!(
            "    {}: ({}) => {{ try {{ {body} }} catch (e) {{ return r.fail(e); }} }},\n",
            js_string(name),
            params.join(", ")
        );
        (function, entry)
    }
}

/// The companion `.mjs` of a module: `snippets(r)` returns the functions of its
/// `dartforge_js` imports by (short) name.
pub fn companion(module_name: &str, snippets: &[(String, Snippet)]) -> String {
    let mut functions = String::new();
    let mut entries = String::new();
    for (index, (name, snippet)) in snippets.iter().enumerate() {
        let (function, entry) = snippet.javascript(name, index);
        functions.push_str(&function);
        entries.push_str(&entry);
    }
    let mut out = String::new();
    writeln!(out, "{COMPANION_HEADER}{module_name}.").unwrap();
    out.push_str(
        "// Its `dart:js_interop` snippets, which the module imports from `dartforge_js`;\n\
         // runtime/wasm/dartforge_host_v1.mjs loads them (docs/WASM-HOST-ABI-V1.md).\n\
         export const abi = 1;\n\
         export function snippets(r) {\n",
    );
    out.push_str(&functions);
    out.push_str("  return {\n");
    out.push_str(&entries);
    out.push_str("  };\n}\n");
    out
}

/// The companion of `module`: the same path with the `.mjs` extension.
pub fn companion_path(module: &Path) -> PathBuf {
    module.with_extension("mjs")
}

/// After the link: renames the snippet imports of `module` to short names and
/// writes its companion next to it. A module without snippets has no companion;
/// a stale one a previous compilation generated is removed.
///
/// # Errors
/// A module that is not WebAssembly, a malformed import section, a snippet
/// import whose name does not decode, or the file system.
pub fn finish_module(module: &Path) -> Result<Option<PathBuf>, String> {
    let bytes =
        std::fs::read(module).map_err(|e| format!("cannot read {}: {e}", module.display()))?;
    let (bytes, snippets) = rename_snippet_imports(&bytes)?;
    let companion_file = companion_path(module);
    if snippets.is_empty() {
        if let Ok(text) = std::fs::read_to_string(&companion_file)
            && text.starts_with(COMPANION_HEADER)
        {
            std::fs::remove_file(&companion_file)
                .map_err(|e| format!("cannot remove {}: {e}", companion_file.display()))?;
        }
        return Ok(None);
    }
    std::fs::write(module, &bytes)
        .map_err(|e| format!("cannot write {}: {e}", module.display()))?;
    let name = module
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    std::fs::write(&companion_file, companion(&name, &snippets))
        .map_err(|e| format!("cannot write {}: {e}", companion_file.display()))?;
    Ok(Some(companion_file))
}

/// The module with each `dartforge_js` import named `s:<hex>` renamed to its
/// index in decimal, and the snippets by new name. The other imports and every
/// other section stay byte for byte.
///
/// # Errors
/// See [`finish_module`].
pub fn rename_snippet_imports(bytes: &[u8]) -> Result<(Vec<u8>, NamedSnippets), String> {
    if bytes.len() < 8 || &bytes[..4] != b"\0asm" {
        return Err("not a WebAssembly module".to_string());
    }
    let mut out = bytes[..8].to_vec();
    let mut snippets = Vec::new();
    let mut at = 8;
    while at < bytes.len() {
        let id = bytes[at];
        let mut cursor = Cursor { bytes, at: at + 1 };
        let size = cursor.leb()? as usize;
        let start = cursor.at;
        let end = start
            .checked_add(size)
            .filter(|&e| e <= bytes.len())
            .ok_or("a section runs past the end of the module")?;
        if id == 2 {
            let payload = rename_in_import_section(&bytes[start..end], &mut snippets)?;
            out.push(2);
            push_leb(&mut out, payload.len() as u64);
            out.extend_from_slice(&payload);
        } else {
            out.extend_from_slice(&bytes[at..end]);
        }
        at = end;
    }
    Ok((out, snippets))
}

fn rename_in_import_section(
    section: &[u8],
    snippets: &mut Vec<(String, Snippet)>,
) -> Result<Vec<u8>, String> {
    let mut cursor = Cursor {
        bytes: section,
        at: 0,
    };
    let count = cursor.leb()?;
    let mut out = Vec::with_capacity(section.len());
    push_leb(&mut out, count);
    for _ in 0..count {
        let module = cursor.name()?;
        let name = cursor.name()?;
        let descriptor_start = cursor.at;
        cursor.skip_import_descriptor()?;
        let descriptor = &section[descriptor_start..cursor.at];
        let new_name = if module == JS_MODULE && name.starts_with(IMPORT_PREFIX) {
            let snippet = Snippet::from_import_name(name)
                .ok_or_else(|| format!("snippet import {name:.40}… does not decode"))?;
            let short = snippets.len().to_string();
            snippets.push((short.clone(), snippet));
            short
        } else {
            name.to_string()
        };
        push_name(&mut out, module);
        push_name(&mut out, &new_name);
        out.extend_from_slice(descriptor);
    }
    if cursor.at != section.len() {
        return Err("trailing bytes in the import section".to_string());
    }
    Ok(out)
}

struct Cursor<'a> {
    bytes: &'a [u8],
    at: usize,
}

impl<'a> Cursor<'a> {
    fn byte(&mut self) -> Result<u8, String> {
        let b = *self
            .bytes
            .get(self.at)
            .ok_or("the import section ends early")?;
        self.at += 1;
        Ok(b)
    }

    fn leb(&mut self) -> Result<u64, String> {
        let mut value = 0u64;
        let mut shift = 0;
        loop {
            let b = self.byte()?;
            if shift >= 64 {
                return Err("LEB128 too long".to_string());
            }
            value |= u64::from(b & 0x7f) << shift;
            if b & 0x80 == 0 {
                return Ok(value);
            }
            shift += 7;
        }
    }

    fn name(&mut self) -> Result<&'a str, String> {
        let len = self.leb()? as usize;
        let end = self
            .at
            .checked_add(len)
            .filter(|&e| e <= self.bytes.len())
            .ok_or("a name runs past the import section")?;
        let s = std::str::from_utf8(&self.bytes[self.at..end])
            .map_err(|_| "an import name is not UTF-8".to_string())?;
        self.at = end;
        Ok(s)
    }

    /// A value or reference type: one byte, or a reference with a heap type
    /// (`0x63`/`0x64` followed by an `s33`).
    fn skip_value_type(&mut self) -> Result<(), String> {
        let b = self.byte()?;
        if b == 0x63 || b == 0x64 {
            self.leb()?;
        }
        Ok(())
    }

    fn skip_limits(&mut self) -> Result<(), String> {
        let flags = self.byte()?;
        self.leb()?;
        if flags & 1 != 0 {
            self.leb()?;
        }
        Ok(())
    }

    fn skip_import_descriptor(&mut self) -> Result<(), String> {
        match self.byte()? {
            // Function: the type index (0x20: the exact-type form).
            0x00 | 0x20 => {
                self.leb()?;
            }
            0x01 => {
                self.skip_value_type()?;
                self.skip_limits()?;
            }
            0x02 => self.skip_limits()?,
            0x03 => {
                self.skip_value_type()?;
                self.byte()?;
            }
            0x04 => {
                self.byte()?;
                self.leb()?;
            }
            other => return Err(format!("unknown import kind 0x{other:02x}")),
        }
        Ok(())
    }
}

fn push_leb(out: &mut Vec<u8>, mut value: u64) {
    loop {
        let b = (value & 0x7f) as u8;
        value >>= 7;
        if value == 0 {
            out.push(b);
            return;
        }
        out.push(b | 0x80);
    }
}

fn push_name(out: &mut Vec<u8>, name: &str) {
    push_leb(out, name.len() as u64);
    out.extend_from_slice(name.as_bytes());
}

fn hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        write!(s, "{b:02x}").unwrap();
    }
    s
}

fn unhex(text: &str) -> Option<Vec<u8>> {
    if !text.len().is_multiple_of(2) {
        return None;
    }
    (0..text.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(text.get(i..i + 2)?, 16).ok())
        .collect()
}

/// `s` as a JavaScript string literal.
fn js_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 => write!(out, "\\u{:04x}", c as u32).unwrap(),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn get_property() -> Snippet {
        Snippet {
            params: vec![Kind::Value, Kind::Text],
            ret: Kind::Value,
            code: "(o, p) => o[p]".to_string(),
        }
    }

    #[test]
    fn symbols_and_import_names_round_trip() {
        let s = get_property();
        assert_eq!(s.signature(), "rs>r");
        assert!(s.symbol().starts_with("dfjs."));
        assert!(s.symbol()[5..].bytes().all(|b| b.is_ascii_hexdigit()));
        assert_eq!(Snippet::from_symbol(&s.symbol()), Some(s.clone()));
        assert_eq!(Snippet::from_import_name(&s.import_name()), Some(s.clone()));
        assert_eq!(
            s.declaration(),
            format!(
                "declare i32 @{}(i32, i32) \"wasm-import-module\"=\"dartforge_js\" \"wasm-import-name\"=\"{}\"",
                s.symbol(),
                s.import_name()
            )
        );
        // A malformed name is not a snippet.
        assert_eq!(Snippet::from_key("v>r|() => 1"), None);
        assert_eq!(Snippet::from_key("r>rr|() => 1"), None);
        assert_eq!(Snippet::from_symbol("dfjs.zz"), None);
        assert_eq!(Snippet::from_symbol("dartforge_allocate"), None);
    }

    #[test]
    fn companion_converts_arguments_results_and_exceptions() {
        let void = Snippet {
            params: vec![Kind::Value, Kind::Value, Kind::Number],
            ret: Kind::Void,
            code: "(o, p, v) => o[p] = v".to_string(),
        };
        let text = companion(
            "app.wasm",
            &[("0".to_string(), get_property()), ("1".to_string(), void)],
        );
        assert!(text.starts_with(COMPANION_HEADER));
        assert!(text.contains("  const f0 = (o, p) => o[p];\n"));
        assert!(text.contains(
            "    \"0\": (a0, a1) => { try { return r.ref(f0(r.get(a0), r.take(a1))); } catch (e) { return r.fail(e); } },\n"
        ));
        assert!(text.contains(
            "    \"1\": (a0, a1, a2) => { try { f1(r.get(a0), r.get(a1), a2); } catch (e) { return r.fail(e); } },\n"
        ));
    }

    #[test]
    fn renames_only_snippet_imports() {
        let s = get_property();
        let wat = format!(
            r#"(module
                 (import "dartforge_host_v1" "write" (func (param i32 i32 i32) (result i32)))
                 (import "dartforge_js" "release" (func (param i32)))
                 (import "dartforge_js" "{}" (func (param i32 i32) (result i32)))
                 (memory (export "memory") 1)
                 (func (export "f") (result i32) i32.const 0))"#,
            s.import_name()
        );
        let module = wat::parse_str(&wat).unwrap();
        let (renamed, snippets) = rename_snippet_imports(&module).unwrap();
        assert_eq!(snippets, vec![("0".to_string(), s)]);
        let names: Vec<(String, String)> = wasmparser::Parser::new(0)
            .parse_all(&renamed)
            .filter_map(|p| match p.unwrap() {
                wasmparser::Payload::ImportSection(section) => Some(
                    section
                        .into_imports()
                        .map(|i| {
                            let i = i.unwrap();
                            (i.module.to_string(), i.name.to_string())
                        })
                        .collect::<Vec<_>>(),
                ),
                _ => None,
            })
            .flatten()
            .collect();
        assert_eq!(
            names,
            [
                ("dartforge_host_v1".to_string(), "write".to_string()),
                ("dartforge_js".to_string(), "release".to_string()),
                ("dartforge_js".to_string(), "0".to_string()),
            ]
        );
        wasmparser::Validator::new().validate_all(&renamed).unwrap();
        // Without snippets the bytes do not change.
        let plain =
            wat::parse_str(r#"(module (import "dartforge_host_v1" "exit" (func (param i32))))"#)
                .unwrap();
        assert_eq!(rename_snippet_imports(&plain).unwrap().0, plain);
    }

    #[test]
    fn finish_writes_and_removes_the_companion() {
        let dir = tempfile::tempdir().unwrap();
        let module = dir.path().join("app.wasm");
        let wat = format!(
            r#"(module (import "dartforge_js" "{}" (func (param i32 i32) (result i32))))"#,
            get_property().import_name()
        );
        std::fs::write(&module, wat::parse_str(&wat).unwrap()).unwrap();
        let companion_file = finish_module(&module).unwrap().unwrap();
        assert_eq!(companion_file, dir.path().join("app.mjs"));
        assert!(
            std::fs::read_to_string(&companion_file)
                .unwrap()
                .contains("app.wasm")
        );
        // Recompiled without interop: the generated companion goes away, a file of
        // the user's with the same name stays.
        std::fs::write(&module, wat::parse_str("(module)").unwrap()).unwrap();
        assert_eq!(finish_module(&module).unwrap(), None);
        assert!(!companion_file.exists());
        std::fs::write(&companion_file, "export const mine = 1;\n").unwrap();
        assert_eq!(finish_module(&module).unwrap(), None);
        assert!(companion_file.exists());
    }
}
