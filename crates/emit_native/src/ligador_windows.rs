//! Linking on Windows through `lld-link` directly, without Visual Studio (MSVC)
//! nor the Windows SDK on the machine of whoever uses dartforge (N15).
//!
//! What the Clang driver, `link.exe` and the MSVC libraries gave the
//! link comes from here, written by us (nothing from MSVC or the Windows SDK is
//! copied or redistributed — their licenses do not allow it):
//!
//! * **import libraries** ([`IMPORTS`]): `ar` files with
//!   COFF *short import* members (`IMPORT_OBJECT_HEADER`, PE/COFF specification
//!   §8), generated from lists with only the names that the runtime, the SDK and the generated
//!   code use — `kernel32`, `ntdll`, `ws2_32`, `advapi32`, `userenv`,
//!   `iphlpapi`, `crypt32`, `bcrypt` and the universal CRT (`ucrtbase.dll`, part
//!   of Windows 10 and later). A name is an interface fact; there is no
//!   one's code in them. `lld-link` builds the import table
//!   by itself from those members;
//! * **the minimal CRT** ([`CRT_COMMON_IR`], [`CRT_EXE_IR`], [`CRT_DLL_IR`]): what
//!   the static CRT (`msvcrt.lib`/`vcruntime.lib`) put into the executable and
//!   `ucrtbase.dll` does not export — the TLS directory (`_tls_used`,
//!   `_tls_index`, the `.tls` and `.CRT$XL*` markers between which Rust
//!   registers its *callbacks*), the `.CRT$XI*`/`.CRT$XC*` initializers,
//!   the `mainCRTStartup`/`_DllMainCRTStartup` entries, the `/GS` cookie
//!   (`__security_cookie`, `__security_check_cookie`, `__GSHandlerCheck`,
//!   which `cl.exe` uses in the C of `ring` and zlib), `__chkstk`, `_fltused`,
//!   `atexit` (over `ucrtbase`'s `_crt_atexit`) and the `type_info` vtable
//!   that the type descriptor of the Rust panic references. It is LLVM
//!   IR compiled by the same generator as the program.
//!
//! Structured exception handling (SEH) and the C++ EH of the Rust panic
//! stay the system's: `__C_specific_handler`, `__CxxFrameHandler3` and
//! `_CxxThrowException` come from `ucrtbase.dll`. The executable no longer depends
//! on `vcruntime140.dll` (which is not part of Windows).
//!
//! The generated files live in a directory ([`SysrootWindows`]): the
//! distribution one (`lib/sysroot/x86_64-pc-windows-msvc/`, generated by
//! `dartforge empacotar`) or, in a development tree, the native cache,
//! generated once per content.

