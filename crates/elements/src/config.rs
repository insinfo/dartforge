//! Reading `.dart_tool/package_config.json` v2 and resolving `package:`
//! URIs.
use crate::generated::Generation;
use dartforge_frontend::LanguageVersion;
use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::sync::Arc;
use url::Url;

/// Information about a package declared in `package_config.json`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PackageInfo {
    pub name: String,
    pub root_uri: Url,
    pub package_uri: Url,
    /// The package's `languageVersion`: the default version of its libraries
    /// (`docs/VERSOES-LINGUAGEM.md`). `None` when the entry does not have one.
    pub language_version: Option<LanguageVersion>,
    /// The text of `languageVersion` when it exists but is not `x.y`: it is a
    /// compile error for the package's libraries (the CFE says
    /// `LanguageVersionInvalidInDotPackages`).
    pub invalid_language_version: Option<String>,
}

/// Mapping of packages to their directories and language versions.
#[derive(Debug, Clone, Default)]
pub struct PackageConfig {
    /// Path of the file read, if any.
    pub origin: Option<PathBuf>,
    pub packages: HashMap<String, PackageInfo>,
    /// `(name, canonical packageUri directory, without the `\\?\` prefix)`,
    /// computed once at load time: mapping a file path to `package:x/…` happens
    /// thousands of times per program and `canonicalize` costs a system call
    /// each time.
    pub package_dirs: Vec<(String, PathBuf)>,
    /// `(name, canonical rootUri directory)`, longest first: tells which package
    /// a file outside `lib/` (`bin/`, `test/`) belongs to, for its default
    /// language version.
    pub root_dirs: Vec<(String, PathBuf)>,
    /// `<project>/.dart_tool/build/generated`, canonical and without `\?\`,
    /// when it exists: the root of the files generated by `build_runner`, mapped
    /// to `package:<package>/<rel>` in `canonical_file_uri`.
    pub generated_root: Option<PathBuf>,
    /// Generated sources in memory (ngdart's `.template.dart` and the like).
    /// When the generation has a file's natural path, it wins: it is the
    /// authority on what it generates itself, and the disk is not even
    /// consulted.
    pub generated_sources: Option<Arc<Generation>>,
    /// Paths (by [`crate::generated::key`]) this load does not see, whether or
    /// not they are on disk: the outputs of `build_runner` phases that the
    /// loading builder cannot read yet (a builder only sees the outputs of the
    /// phases before its own). Importing one of them stays unresolved, as in the
    /// official `BuildStep.resolver`.
    pub hidden: Option<Arc<std::collections::HashSet<PathBuf>>>,
}

/// Strips the `\\?\` verbatim prefix `canonicalize` returns on Windows, so
/// that `strip_prefix` and comparisons with plain paths work.
pub fn without_verbatim(p: PathBuf) -> PathBuf {
    match p.to_str().and_then(|s| s.strip_prefix(r"\\?\")) {
        Some(r) => PathBuf::from(r),
        None => p,
    }
}

impl PackageConfig {
    /// Is the path among this load's [`PackageConfig::hidden`]?
    pub fn is_hidden(&self, path: &Path) -> bool {
        self.hidden
            .as_ref()
            .is_some_and(|o| o.contains(&crate::generated::key(path)))
    }

    /// The package the library with URI `uri` (file at `path`) belongs to, by
    /// the rule of `accepted/2.8/language-versioning`: `package:x/…` belongs to
    /// `x`; a file belongs to the package whose root (`rootUri`) contains it,
    /// the innermost one when they nest.
    pub fn library_package(&self, uri: &str, path: Option<&Path>) -> Option<&PackageInfo> {
        if let Some(rest) = uri.strip_prefix("package:") {
            let name_ = rest.split('/').next().unwrap_or("");
            return self.packages.get(name_);
        }
        let path = path?;
        self.root_dirs
            .iter()
            .find(|(_, dir)| path.starts_with(dir))
            .and_then(|(name_, _)| self.packages.get(name_))
    }

    /// Path of a file generated by build_runner, when it exists:
    /// `<project>/.dart_tool/build/generated/<package>/lib/<rel>` (the project
    /// owns the `package_config.json` read).
    pub fn generated_path(&self, pkg_name: &str, rel_path: &str) -> Option<PathBuf> {
        let origin = self.origin.as_ref()?;
        let dart_tool = origin.parent()?;
        let candidate = dart_tool
            .join("build")
            .join("generated")
            .join(pkg_name)
            .join("lib")
            .join(rel_path);
        candidate.is_file().then_some(candidate)
    }

    /// The file generated by `build_runner` that takes the place of `path`, a
    /// file in any folder of a package (not just `lib/`: `test/`, `web/`,
    /// `example/`): `<project>/.dart_tool/build/generated/<package>/<rel>`, with
    /// `rel` relative to the root (`rootUri`) of the innermost package that
    /// contains it. It is the overlay the analyzer applies to generated files.
    ///
    /// ```
    /// use dartforge_elements::PackageConfig;
    /// // Without `.dart_tool/build/generated`, nothing is overlaid.
    /// assert!(PackageConfig::default().generated_in_place_of(std::path::Path::new("/p/test/a.template.dart")).is_none());
    /// ```
    pub fn generated_in_place_of(&self, path: &Path) -> Option<PathBuf> {
        if self.is_hidden(path) {
            return None;
        }
        let generated_root_dir = self.generated_root.as_ref()?;
        let (name_, root) = self
            .root_dirs
            .iter()
            .find(|(_, dir)| path.starts_with(dir))?;
        let rel = path.strip_prefix(root).ok()?;
        let candidate = generated_root_dir.join(name_).join(rel);
        candidate.is_file().then_some(candidate)
    }

    /// The original place of a generated file (the inverse of
    /// [`PackageConfig::generated_in_place_of`]): `…/generated/<package>/<rel>` →
    /// `<package root>/<rel>`. A generated file's relative imports resolve from
    /// there, as in the analyzer.
    pub fn generated_origin(&self, path: &Path) -> Option<PathBuf> {
        let rel = path.strip_prefix(self.generated_root.as_ref()?).ok()?;
        let mut parts = rel.iter();
        let name_ = parts.next()?.to_str()?;
        let root = &self.root_dirs.iter().find(|(n, _)| n == name_)?.1;
        Some(root.join(parts.as_path()))
    }

    /// Finds the `package_config.json` file, searching from the directory of
    /// `entry` and walking up the directory tree.
    pub fn discover(entry: &Path) -> Option<PathBuf> {
        let parent = if entry.is_dir() {
            entry
        } else {
            entry.parent()?
        };
        for dir in parent.ancestors() {
            let candidate = dir.join(".dart_tool").join("package_config.json");
            if candidate.is_file() {
                return Some(candidate);
            }
        }
        None
    }

    /// Loads and validates the `.dart_tool/package_config.json` v2 file.
    ///
    /// # Errors
    /// Returns a message on I/O failure, invalid JSON or a `configVersion`
    /// other than 2.
    pub fn load(path: &Path) -> Result<Self, String> {
        let text = std::fs::read_to_string(path)
            .map_err(|e| format!("could not read {}: {e}", path.display()))?;
        let json: serde_json::Value = serde_json::from_str(&text)
            .map_err(|e| format!("invalid JSON in {}: {e}", path.display()))?;

        if json.get("configVersion").and_then(|v| v.as_u64()) != Some(2) {
            return Err(format!("configVersion of {} must be 2", path.display()));
        }

        let entries = json
            .get("packages")
            .and_then(|v| v.as_array())
            .ok_or_else(|| format!("field 'packages' missing in {}", path.display()))?;

        let canonical_dir = path
            .parent()
            .and_then(|p| p.canonicalize().ok())
            .unwrap_or_else(|| path.parent().unwrap_or(Path::new(".")).to_path_buf());
        let base_url = Url::from_directory_path(&canonical_dir)
            .map_err(|_| format!("invalid path for URL: {}", canonical_dir.display()))?;

        let mut packages = HashMap::new();
        for entry in entries {
            let name = entry
                .get("name")
                .and_then(|v| v.as_str())
                .ok_or_else(|| format!("package without a name in {}", path.display()))?;

            let root_str = entry
                .get("rootUri")
                .and_then(|v| v.as_str())
                .ok_or_else(|| format!("package '{name}' without rootUri in {}", path.display()))?;
            // `rootUri` is a directory but pub writes it without a trailing `/`
            // (`.../collection-1.19.1`); without the slash, `join("lib/")` would replace
            // the last segment instead of descending into it.
            let root_dir = if root_str.ends_with('/') {
                root_str.to_string()
            } else {
                format!("{root_str}/")
            };
            let root_uri = base_url
                .join(&root_dir)
                .map_err(|e| format!("invalid rootUri in '{name}': {e}"))?;

            let package_str = entry
                .get("packageUri")
                .and_then(|v| v.as_str())
                .unwrap_or("");
            // Makes sure package_uri ends with '/' so child files can be joined
            let normalized_pkg = if package_str.is_empty() || package_str.ends_with('/') {
                package_str.to_string()
            } else {
                format!("{package_str}/")
            };
            let package_uri = root_uri
                .join(&normalized_pkg)
                .map_err(|e| format!("invalid packageUri in '{name}': {e}"))?;

            let version_text = entry.get("languageVersion").and_then(|v| v.as_str());
            let language_version = version_text.and_then(LanguageVersion::parse);
            let invalid_language_version = version_text
                .filter(|_| language_version.is_none())
                .map(str::to_string);

            packages.insert(
                name.to_string(),
                PackageInfo {
                    name: name.to_string(),
                    root_uri,
                    package_uri,
                    language_version,
                    invalid_language_version,
                },
            );
        }

        let mut root_dirs: Vec<(String, PathBuf)> = packages
            .values()
            .filter_map(|pkg| {
                let dir = pkg.root_uri.to_file_path().ok()?;
                let dir = without_verbatim(std::fs::canonicalize(&dir).unwrap_or(dir));
                Some((pkg.name.clone(), dir))
            })
            .collect();
        root_dirs.sort_by(|a, b| {
            b.1.as_os_str()
                .len()
                .cmp(&a.1.as_os_str().len())
                .then(a.0.cmp(&b.0))
        });

        let mut package_dirs: Vec<(String, PathBuf)> = packages
            .values()
            .filter_map(|pkg| {
                let dir = pkg.package_uri.to_file_path().ok()?;
                let dir = without_verbatim(std::fs::canonicalize(&dir).unwrap_or(dir));
                Some((pkg.name.clone(), dir))
            })
            .collect();
        // Longest directory first: a package inside another matches the most
        // specific one.
        package_dirs.sort_by(|a, b| {
            b.1.as_os_str()
                .len()
                .cmp(&a.1.as_os_str().len())
                .then(a.0.cmp(&b.0))
        });

        let generated_root = path
            .parent()
            .map(|dart_tool| dart_tool.join("build").join("generated"))
            .filter(|g| g.is_dir())
            .map(|g| without_verbatim(std::fs::canonicalize(&g).unwrap_or(g)));

        Ok(Self {
            origin: Some(path.to_path_buf()),
            packages,
            package_dirs,
            root_dirs,
            generated_root,
            generated_sources: None,
            hidden: None,
        })
    }

    /// Resolves a `package:name/path.dart` URI to a local file path.
    pub fn resolve_package_uri(&self, uri: &str) -> Result<PathBuf, String> {
        let remainder = uri
            .strip_prefix("package:")
            .ok_or_else(|| format!("expected the 'package:' prefix, got '{uri}'"))?;
        let slash = remainder
            .find('/')
            .ok_or_else(|| format!("invalid package URI (no '/'): '{uri}'"))?;
        let pkg_name = &remainder[..slash];
        let rel_path = &remainder[slash + 1..];

        if let Some(pkg) = self.packages.get(pkg_name) {
            let file_url = pkg
                .package_uri
                .join(rel_path)
                .map_err(|e| format!("could not build a file URI for '{uri}': {e}"))?;

            let path = file_url
                .to_file_path()
                .map_err(|_| format!("URL does not represent a local file: {file_url}"))?;
            if self
                .generated_sources
                .as_ref()
                .is_some_and(|g| g.contains(&path))
            {
                return Ok(path);
            }
            if path.is_file() {
                return Ok(path);
            }
            // Overlay of build_runner generated files (ngdart's `.template.dart`…):
            // `<project root>/.dart_tool/build/generated/<package>/lib/<x>`.
            if let Some(generated) = self.generated_path(pkg_name, rel_path) {
                return Ok(generated);
            }
            Ok(path)
        } else {
            // Fallback: looks in references/pub/<pkg_name>-<version>/lib/<rel_path>
            let pub_dir = Path::new("references/pub");
            if pub_dir.is_dir() {
                if let Ok(entries) = std::fs::read_dir(pub_dir) {
                    for entry in entries.flatten() {
                        let path = entry.path();
                        if path.is_dir() {
                            if let Some(folder_name) = path.file_name().and_then(|n| n.to_str()) {
                                if folder_name == pkg_name
                                    || folder_name.starts_with(&format!("{pkg_name}-"))
                                {
                                    let candidate = path.join("lib").join(rel_path);
                                    if candidate.exists() {
                                        return candidate.canonicalize().or(Ok(candidate));
                                    }
                                }
                            }
                        }
                    }
                }
            }

            let origin = self
                .origin
                .as_ref()
                .map(|p| p.display().to_string())
                .unwrap_or_else(|| "configuration not found".to_string());
            Err(format!("package '{pkg_name}' not mapped in {origin}"))
        }
    }
}
