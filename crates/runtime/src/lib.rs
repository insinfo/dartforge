//! Native runtime with a precise heap, strings, objects, cells, environments and lists.
//! See CONTRACT.md at the root of the crate.
//!
//! # One source, two compilations
//!
//! The runtime that generated code calls is the concatenation of the fragments
//! `src/<fragment>.rs` in the order of `FRAGMENTOS` in `build.rs` ([`simbolos::FRAGMENTOS`]):
//! `core` (entry, per-thread state, objects, boxes), `gc_roots`, `exceptions`,
//! `output`, `strings`, `collections`, `closures` and the rest. The AOT compiles the
//! concatenated text ([`RUNTIME_MAIN`]) with a standalone `rustc` and links the `.lib`
//! into the executable. The JIT (`crates/jit`) uses the **same files** compiled here,
//! as the [`abi`] module, and publishes the addresses from [`simbolos::tabela`]. The
//! semantic flags are the same in both (opt-level 2, no overflow-checks, no
//! debug-assertions): the root `Cargo.toml` pins this crate's profile to what the
//! AOT's `rustc -O` gives. The `tests/single_source.rs` test checks it.
pub mod hash;
/// The compressed form of the RTI table (compiler and runtime).
pub mod tabela_rti;
/// The ARC core with cycle collection (docs/ARC-CICLOS-ESPECIFICACAO.md §19, §22).
pub mod arc;
pub mod heap;
/// The block layout contract (docs/NATIVO-ESPACO-UNIFICADO.md §3.1).
pub mod layout;
/// The object space (pages, size classes, large regions, sweeping).
pub mod space;
/// The per-kind views of the unified space (§3.3): strings, boxes, lists and
/// typed lists, each one an `impl Heap` over the `heap` API.
pub mod textos;
pub mod boxes;
pub mod lists;
pub mod tipadas;

/// The runtime harness, compiled as a module: everything the AOT executable
/// links, except the C `main` (cfg `dartforge_runtime_embutido`, from `build.rs`).
/// The body is one `include!` per fragment, in the order of `FRAGMENTOS`.
///
/// The `allow`s are the same the AOT applies (`#![allow(warnings)]` in the
/// standalone compilation): the file is the same code in both profiles, not a
/// version adjusted to the workspace lints.
#[allow(warnings, unsafe_code, unsafe_op_in_unsafe_fn, clippy::all)]
pub mod abi {
    include!(concat!(env!("OUT_DIR"), "/abi.rs"));
}

/// The `(name, address)` table of the runtime symbols and the list of
/// fragments, generated by `build.rs` from the `#[unsafe(no_mangle)]` functions
/// of all the fragments.
pub mod simbolos {
    include!(concat!(env!("OUT_DIR"), "/simbolos.rs"));
}

/// The extern effects table — what each runtime function may do (collect,
/// leave a pending exception, run Dart code) —, generated by `build.rs` from
/// `efeitos.tsv` (docs/NATIVO-MAPAS-DE-PILHA-E-EXCECOES.md §13.8). The emitter
/// uses it to decide where to check for a pending exception and what is a
/// collection point.
pub mod efeitos {
    include!(concat!(env!("OUT_DIR"), "/efeitos.rs"));
}

/// Audited ownership contracts, generated from `ownership.tsv`.
/// The catalog is being migrated: absence does not authorize an implicit borrow.
pub mod ownership {
    include!(concat!(env!("OUT_DIR"), "/ownership.rs"));

    /// Gets an audited contract without assigning a borrow to absent symbols.
    ///
    /// # Errors
    /// Returns an error when the symbol does not have an explicit contract yet.
    ///
    /// ```
    /// use dartforge_runtime::ownership::{contrato, ModoResultado};
    /// assert_eq!(contrato("dartforge_arc_quadro_carregar_v1").unwrap().resultado, ModoResultado::Owned);
    /// assert!(contrato("dartforge_alocar").is_err());
    /// ```
    pub fn contrato(nome: &str) -> Result<&'static Contrato, &'static str> {
        CONTRATOS
            .iter()
            .find(|c| c.nome == nome)
            .ok_or("extern without an explicit ownership contract")
    }
}

