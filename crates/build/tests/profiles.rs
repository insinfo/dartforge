//! Version profiles of the build engine (DF-BUILD-011) against the oracle of
//! the official `build_runner` of each version: `corpus/builders/perfil_2_4`
//! (`build_runner` 2.4.15, `build_config` 1.1.2, Dart 3.6.2) and
//! `corpus/builders_novos/perfil_2_16` (`build_runner` 2.16.1, `build_config`
//! 1.3.3, Dart 3.13.4). Each case has one oracle per configuration
//! (`oraculos/<name>/manifesto.json`, with the official tool's command-line
//! arguments): default, `--release`, `--define`, `--config alt` and
//! `--build-filter`. The `build.yaml` covers defaults, target, global,
//! dev/release, explicit disabling (`enabled: false` and
//! `run_only_if_triggered: false`) and, in 2.16, annotation triggers (direct,
//! with a prefix, in a hand-written part and in a part generated by an earlier
//! phase) and import triggers (including the one a support package adds).
//!
//! The comparison goes both ways: the set of outputs written by the engine
//! must be exactly the oracle's, byte for byte.
//!
//! Prerequisites, hence `#[ignore]`: the Dart 3.6.2 VM
//! (`DARTFORGE_BUILD_DART`, `DARTFORGE_DART_SDK/bin/dart` or `dart` on the
//! `PATH`) and `dart pub get --enforce-lockfile` in `corpus/builders/perfil_2_4`
//! (CI does it). The builders of the 2.16 case run on the same VM with the 2.4
//! dependencies (`build` 2.4.2): their code only uses the API common to both
//! versions, and the 2.4 `package_config.json` gives the engine the same
//! package graph (no resolved package other than the root defines builders).
//! What decides the profile is the 2.16 case's `pubspec.lock`.
use dartforge_build::consulta::SemBanco;
use dartforge_build::grafo::AssetId;
use dartforge_build::linha_de_comando::OpcoesDoBuild;
use dartforge_build::vm::{ConfigDaVm, ExecutorVm};
use dartforge_build::{Contexto, Demanda, Motor, OpcoesMotor, RelMotor};
use dartforge_elements::config::PackageConfig;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

fn corpus() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../corpus")
}

fn case_2_4() -> PathBuf {
    corpus().join("builders/perfil_2_4")
}

fn case_2_16() -> PathBuf {
    corpus().join("builders_novos/perfil_2_16")
}

fn dart() -> PathBuf {
    dartforge_build::vm::dart_do_ambiente()
        .or_else(|| {
            std::env::var_os("DARTFORGE_DART_SDK")
                .map(|s| PathBuf::from(s).join("bin").join("dart"))
        })
        .unwrap_or_else(|| PathBuf::from("dart"))
}

/// Copy of the case without oracles or `.dart_tool`: no output of the
/// official tool on disk, everything must come from the executor.
fn copy_case(from: &Path, to: &Path) {
    std::fs::create_dir_all(to).unwrap();
    for e in std::fs::read_dir(from).unwrap().flatten() {
        let name = e.file_name();
        if name == "oraculos" || name == ".dart_tool" || name == "build" {
            continue;
        }
        let p = e.path();
        if p.is_dir() {
            copy_case(&p, &to.join(&name));
        } else {
            std::fs::copy(&p, to.join(&name)).unwrap();
        }
    }
}

/// The `package_config.json` of the 2.4 case (resolved by `pub get`), with the
/// root package renamed to `root`.
fn package_config(destination: &Path, root: &str) {
    let origin = case_2_4().join(".dart_tool/package_config.json");
    let text = std::fs::read_to_string(&origin).unwrap_or_else(|e| {
        panic!(
            "{}: {e} (dart pub get in corpus/builders/perfil_2_4)",
            origin.display()
        )
    });
    let mut v: serde_json::Value = serde_json::from_str(&text).unwrap();
    for p in v["packages"].as_array_mut().unwrap() {
        if p["name"] == "corpus_perfil_2_4" {
            p["name"] = root.into();
        }
    }
    let dir = destination.join(".dart_tool");
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(dir.join("package_config.json"), v.to_string()).unwrap();
}

struct Oracle {
    arguments: Vec<String>,
    outputs: BTreeMap<AssetId, Vec<u8>>,
}

fn oracle(case: &Path, name: &str) -> Oracle {
    let dir = case.join("oraculos").join(name);
    let m: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(dir.join("manifesto.json")).unwrap())
            .unwrap();
    let arguments = m["argumentos"]
        .as_array()
        .unwrap()
        .iter()
        .map(|a| a.as_str().unwrap().to_string())
        .collect();
    let mut outputs = BTreeMap::new();
    for s in m["saidas"].as_array().unwrap() {
        let id = AssetId::de_texto(s["asset"].as_str().unwrap()).unwrap();
        let file = match s["build_to"].as_str() {
            Some("source") => dir.join("source").join(id.caminho.as_ref()),
            _ => dir
                .join("cache")
                .join(id.pacote.as_ref())
                .join(id.caminho.as_ref()),
        };
        outputs.insert(id, std::fs::read(&file).unwrap());
    }
    Oracle { arguments, outputs }
}

/// The engine options for the oracle's `build_runner` arguments.
fn options(dir: &Path, arguments: &[String]) -> OpcoesMotor {
    let (mut release, mut config, mut defines, mut filters) = (false, None, Vec::new(), Vec::new());
    let mut it = arguments.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--release" => release = true,
            "--config" => config = it.next().cloned(),
            "--define" => defines.push(it.next().unwrap().clone()),
            "--build-filter" => filters.push(it.next().unwrap().clone()),
            o => panic!("argument without a translation: {o}"),
        }
    }
    let mut o = OpcoesMotor {
        release,
        trabalhadores: 1,
        ..OpcoesMotor::default()
    };
    OpcoesDoBuild::do_projeto(dir, config.as_deref(), &defines, &filters)
        .expect("options")
        .aplicar(&mut o);
    o
}

fn engine(dir: &Path, options: OpcoesMotor) -> Motor {
    let cfg =
        PackageConfig::load(&dir.join(".dart_tool/package_config.json")).expect("package_config");
    let mut m = Motor::novo(dir, &cfg, options).expect("engine");
    m.definir_executor_dart(Box::new(ExecutorVm::novo(ConfigDaVm::do_projeto(
        dart(),
        dir,
    ))));
    m
}

fn update(m: &mut Motor, changed: &[PathBuf]) -> RelMotor {
    let at = m
        .atualizar(
            &Contexto {
                banco: &SemBanco,
                programa: None,
            },
            changed,
            Demanda::Tudo,
        )
        .expect("update");
    at.rel
}

/// The outputs the engine wrote (`Some` content in the record).
fn written(m: &Motor) -> BTreeMap<AssetId, Vec<u8>> {
    let mut v = BTreeMap::new();
    for (id, g) in &m.grafo.gerados {
        if let Some(c) = m
            .registro(g.acao)
            .and_then(|r| r.saidas.iter().find(|(s, _)| s == id))
            .and_then(|(_, c)| c.clone())
        {
            v.insert(id.clone(), c.to_vec());
        }
    }
    v
}

/// Differences between what the engine wrote and the oracle, both ways.
fn differences(
    actual: &BTreeMap<AssetId, Vec<u8>>,
    expected: &BTreeMap<AssetId, Vec<u8>>,
) -> Vec<String> {
    let mut d = Vec::new();
    for (id, b) in expected {
        match actual.get(id) {
            None => d.push(format!("missing {}", id.texto())),
            Some(o) if o != b => d.push(format!(
                "differs {}:\n--- official\n{}\n--- engine\n{}",
                id.texto(),
                String::from_utf8_lossy(b),
                String::from_utf8_lossy(o)
            )),
            _ => {}
        }
    }
    for id in actual.keys() {
        if !expected.contains_key(id) {
            d.push(format!("extra {}", id.texto()));
        }
    }
    d
}

/// Runs the case's configuration `name` and compares it with the oracle.
fn check(case: &Path, root: &str, name: &str) {
    let o = oracle(case, name);
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path().join(root);
    copy_case(case, &dir);
    package_config(&dir, root);
    let mut m = engine(&dir, options(&dir, &o.arguments));
    let rel = update(&mut m, &[]);
    println!("{name}: {}", rel.texto());
    assert!(rel.falhas.is_empty(), "{name}: {}", rel.texto());
    let d = differences(&written(&m), &o.outputs);
    assert!(
        d.is_empty(),
        "{name} ({:?}):\n{}",
        o.arguments,
        d.join("\n")
    );
}

#[test]
#[ignore = "requires the Dart VM and `dart pub get` in corpus/builders/perfil_2_4"]
fn profile_2_4_equals_build_runner_2_4_15() {
    for name in ["padrao", "release", "define", "config_alt", "filtro"] {
        check(&case_2_4(), "corpus_perfil_2_4", name);
    }
}

#[test]
#[ignore = "requires the Dart VM and `dart pub get` in corpus/builders/perfil_2_4"]
fn profile_2_16_equals_build_runner_2_16_1() {
    for name in ["padrao", "release", "define", "config_alt", "filtro"] {
        check(&case_2_16(), "corpus_perfil_2_16", name);
    }
}

/// Triggers are reevaluated by what they read: the input and the parts. Each
/// edit, after the incremental update, gives the same as a new engine.
#[test]
#[ignore = "requires the Dart VM and `dart pub get` in corpus/builders/perfil_2_4"]
fn profile_2_16_incremental_triggers() {
    let root = "corpus_perfil_2_16";
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path().join(root);
    copy_case(&case_2_16(), &dir);
    package_config(&dir, root);
    let mut m = engine(&dir, options(&dir, &[]));
    update(&mut m, &[]);
    assert_eq!(
        differences(&written(&m), &oracle(&case_2_16(), "padrao").outputs),
        Vec::<String>::new()
    );
    let id = |c: &str| AssetId::novo(root, c);
    let edits: [(&str, &str, &str, bool); 3] = [
        // The relative import becomes `package:`: `importacao` starts firing.
        (
            "lib/relativo.dart",
            "import 'package:corpus_perfil_2_16/marcador.dart';\n\nconst valor = marcador;\n",
            "lib/relativo.importacao.txt",
            true,
        ),
        // The part loses the annotation: `com_parte.dart` stops firing.
        (
            "lib/com_parte_detalhe.dart",
            "part of 'com_parte.dart';\n\nclass Detalhe {}\n",
            "lib/com_parte.anotacao.txt",
            false,
        ),
        // The member becomes an annotated top-level declaration.
        (
            "lib/membro.dart",
            "import 'anotacoes.dart';\n\n@Gerar()\nvoid metodo() {}\n",
            "lib/membro.anotacao.txt",
            true,
        ),
    ];
    for (file, text, output, exists) in edits {
        let p = dir.join(file);
        std::fs::write(&p, text).unwrap();
        let rel = update(&mut m, &[p]);
        println!("{file}: {}", rel.texto());
        let incremental = written(&m);
        assert_eq!(
            incremental.contains_key(&id(output)),
            exists,
            "{file}: {output}"
        );
        let mut fresh = engine(&dir, options(&dir, &[]));
        update(&mut fresh, &[]);
        assert_eq!(
            differences(&incremental, &written(&fresh)),
            Vec::<String>::new(),
            "{file}"
        );
    }
}
