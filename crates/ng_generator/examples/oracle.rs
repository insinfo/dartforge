//! Compares what the generator produces with what the official ngdart
//! compiler produced, file by file.
//!
//! The `.template.dart` files that `build_runner` has already written to
//! `.dart_tool/build/generated` are the generator's oracle, just as `dartdevc`
//! is the emitter's oracle. While the scoreboard is not complete, what is
//! missing keeps coming from the official compiler and the application
//! compiles all the same.
//!
//! ```text
//! cargo run -p dartforge-ng-generator --example oracle -- C:/MyDartProjects/new_sali/frontend
//! ```
use dartforge_elements::config::PackageConfig;
use dartforge_elements::generated::{GenerationBuilder, from_build_runner};
use dartforge_elements::load::load_lenient_entries_hiding;
use dartforge_elements::sdk::SdkLayout;
use dartforge_intern::Interner;
use dartforge_ng_generator::resolution::Resolver;
use dartforge_ng_generator::{Package, Scoreboard, template_path, generate_in};
use std::path::PathBuf;

fn main() -> std::process::ExitCode {
    let mut args = std::env::args().skip(1);
    let Some(root) = args.next().map(PathBuf::from) else {
        eprintln!("usage: oracle <project root> [--list] [--all] [--dump <dir>]");
        return std::process::ExitCode::FAILURE;
    };
    // Absolute path: the URIs of `package_config.json` are absolute, and
    // comparing with a relative path matches nothing.
    let root =
        dartforge_elements::config::without_verbatim(std::fs::canonicalize(&root).unwrap_or(root));
    let rest: Vec<String> = args.collect();
    let list = rest.iter().any(|a| a == "--list");
    // `--all`: also the dependencies with official ngdart output (the hosted
    // `limitless_ui`, ngdart itself, ngforms…), which `serve` requests just
    // like those of the entry package.
    let all = rest.iter().any(|a| a == "--all");
    // `--dump <dir>`: writes ours and the official one for each differing
    // file, to compare with a diff.
    let dump = rest
        .iter()
        .position(|a| a == "--dump")
        .and_then(|i| rest.get(i + 1))
        .map(PathBuf::from);

    let cfg_path = root.join(".dart_tool").join("package_config.json");
    let cfg = match PackageConfig::load(&cfg_path) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("could not read {}: {e}", cfg_path.display());
            return std::process::ExitCode::FAILURE;
        }
    };
    let official = from_build_runner(&cfg, &[".template.dart", ".css.shim.dart"], None);
    println!(
        "official: {} files generated by build_runner",
        official.len()
    );
    // The `.css` stylesheets that this build's `sass_builder` wrote: the ngdart
    // shim starts from them, as in the engine (which receives them from the
    // native Sass). The oracle measures the ngdart compiler; Sass has its own
    // (`crates/sass`), and each package compiles in the style and with the
    // dart-sass version of its own.
    let official_css = from_build_runner(&cfg, &[".css"], None);
    let stylesheets_of = |dir: &std::path::Path| -> std::collections::HashMap<PathBuf, String> {
        official_css
            .iter()
            .filter(|(p, _)| p.starts_with(dir))
            .map(|(p, f)| (p.clone(), f.content.to_string()))
            .collect()
    };

    // Phase 1: load the project without the generated files. The load is
    // lenient, so the missing `.template.dart` files become diagnostics and
    // the rest of the program stands — which is all the generator needs to
    // resolve names.
    let Some(package_name) = dartforge_ng_generator::read_package_name(&root) else {
        eprintln!("no `name:` in the pubspec.yaml of {}", root.display());
        return std::process::ExitCode::FAILURE;
    };
    // The dependencies the oracle covers: those with official output in
    // `.dart_tool/build/generated/<package>/lib`.
    let mut dependencies: Vec<(String, PathBuf)> = Vec::new();
    if all {
        let generated = root.join(".dart_tool").join("build").join("generated");
        for (name, pkg) in &cfg.packages {
            if *name == package_name || !generated.join(name).join("lib").is_dir() {
                continue;
            }
            // The ngdart compiler does not enter the application program (DDC
            // never requests its generated files), and loading it would bring
            // in the whole `analyzer`.
            if matches!(
                name.as_str(),
                "ngcompiler" | "ngx_compiler" | "ngast" | "ngx_ast"
            ) {
                continue;
            }
            if let Ok(dir) = pkg.root_uri.to_file_path() {
                let dir = dartforge_elements::config::without_verbatim(
                    std::fs::canonicalize(&dir).unwrap_or(dir),
                );
                dependencies.push((name.clone(), dir));
            }
        }
        dependencies.sort();
    }
    let (roots, hidden) = all_files(&root, &dependencies);
    let sdk_dir =
        SdkLayout::discover().unwrap_or_else(|| PathBuf::from("C:/tools/dartsdk-3.6.2/lib"));
    let sdk = match SdkLayout::load(&sdk_dir, "dartdevc") {
        Ok(s) => s,
        Err(e) => {
            eprintln!("SDK unavailable ({e}); the scoreboard comes out without name resolution");
            return scoreboard_without_resolution(&root, &cfg, &official);
        }
    };
    let mut names = Interner::new();
    let t = std::time::Instant::now();
    let roots: Vec<&std::path::Path> = roots.iter().map(PathBuf::as_path).collect();
    let (program, _) = load_lenient_entries_hiding(
        &roots,
        &sdk,
        Some(&cfg_path),
        &mut names,
        std::sync::Arc::new(hidden),
    );
    println!(
        "program: {} libraries in {} ms",
        program.libraries.len(),
        t.elapsed().as_millis()
    );
    let resolver = Resolver::new(&program, &names);

    let mut interner = Interner::new();
    let mut c = GenerationBuilder::new();
    let mut scoreboard = Scoreboard::default();
    let dirs: Vec<PathBuf> = ["lib", "web", "test"]
        .iter()
        .map(|d| root.join(d))
        .filter(|d| d.is_dir())
        .collect();
    let package = Package {
        name: package_name,
        root: root.clone(),
        generated_sheets: stylesheets_of(&root),
    };
    println!("package: {}", package.name);
    generate_in(
        &package,
        &dirs,
        &mut interner,
        &mut c,
        &mut scoreboard,
        Some(&resolver),
    );
    for (name, dir) in &dependencies {
        let package = Package {
            name: name.clone(),
            root: dir.clone(),
            generated_sheets: stylesheets_of(dir),
        };
        generate_in(
            &package,
            &[dir.join("lib")],
            &mut interner,
            &mut c,
            &mut scoreboard,
            Some(&resolver),
        );
    }
    let ours = match c.finish(1) {
        Ok(g) => g,
        Err(errors) => {
            for m in errors {
                eprintln!("error: {m}");
            }
            return std::process::ExitCode::FAILURE;
        }
    };

    let (mut equal, mut different, mut no_official) = (0usize, 0usize, 0usize);
    let mut divergent: Vec<String> = Vec::new();
    for (path, f) in ours.iter() {
        match official.get(path) {
            None => no_official += 1,
            Some(o) if o.content == f.content => equal += 1,
            Some(o) => {
                different += 1;
                if let Some(d) = &dump {
                    let name = path
                        .file_name()
                        .unwrap_or_default()
                        .to_string_lossy()
                        .to_string();
                    let _ = std::fs::create_dir_all(d);
                    let _ = std::fs::write(d.join(format!("{name}.ours")), f.content.as_bytes());
                    let _ =
                        std::fs::write(d.join(format!("{name}.official")), o.content.as_bytes());
                }
                // The first diverging line says more than the file name.
                let expected = o.content.replace("\r\n", "\n");
                let first = expected
                    .lines()
                    .zip(f.content.lines())
                    .enumerate()
                    .find(|(_, (a, b))| a != b)
                    .map(|(i, (a, b))| {
                        format!(
                            "
    line {}
    official: {a}
    ours:     {b}",
                            i + 1
                        )
                    })
                    .unwrap_or_default();
                divergent.push(format!("{}{first}", path.display()));
            }
        }
    }
    // Pending files with an official output: the shapes still to be learned.
    let pending_with_official = scoreboard
        .pending
        .iter()
        .filter(|p| official.contains(&template_path(p)))
        .count();

    println!("examined: {}", scoreboard.examined);
    println!("  generated by us: {}", scoreboard.generated);
    println!("    equal to official: {equal}");
    println!("    different:         {different}");
    println!("    no official:       {no_official}");
    println!(
        "  pending: {} ({pending_with_official} with official)",
        scoreboard.pending.len()
    );
    // In how many files each reason and each sub-shape appears, and how many
    // each one unlocks on its own (the file where it is the only refusal).
    let mut appears: std::collections::BTreeMap<_, usize> = Default::default();
    let mut alone: std::collections::BTreeMap<_, usize> = Default::default();
    let mut shape_appears: std::collections::BTreeMap<_, usize> = Default::default();
    let mut shape_alone: std::collections::BTreeMap<_, usize> = Default::default();
    for set in &scoreboard.refusal_sets {
        let reasons: std::collections::BTreeSet<_> = set.iter().map(|r| r.reason).collect();
        for m in &reasons {
            *appears.entry(*m).or_default() += 1;
        }
        if reasons.len() == 1 {
            *alone.entry(*reasons.iter().next().unwrap()).or_default() += 1;
        }
        for r in set {
            *shape_appears.entry(r.clone()).or_default() += 1;
        }
        if set.len() == 1 {
            *shape_alone
                .entry(set.iter().next().unwrap().clone())
                .or_default() += 1;
        }
    }
    println!("  reasons (appears / unlocks alone):");
    let mut lines: Vec<_> = appears.iter().map(|(m, n)| (*n, *m)).collect();
    lines.sort_by_key(|a| std::cmp::Reverse(a.0));
    for (n, m) in lines {
        println!(
            "    {n:4} / {:4}  {}",
            alone.get(&m).copied().unwrap_or(0),
            m.text()
        );
    }
    println!("  sub-shapes (appears / unlocks alone):");
    let mut shapes: Vec<_> = shape_appears.iter().map(|(r, n)| (*n, r.clone())).collect();
    shapes.sort_by(|a, b| b.0.cmp(&a.0).then_with(|| a.1.cmp(&b.1)));
    for (n, r) in shapes {
        println!(
            "    {n:4} / {:4}  {}",
            shape_alone.get(&r).copied().unwrap_or(0),
            r.text()
        );
    }
    if !scoreboard.not_understood.is_empty() {
        println!("  shapes not understood:");
        let mut v: Vec<_> = scoreboard
            .not_understood
            .iter()
            .map(|(k, n)| (*n, k))
            .collect();
        v.sort_by_key(|a| std::cmp::Reverse(a.0));
        for (n, shape) in v.iter().take(12) {
            println!("    {n:4}  {shape}");
        }
    }
    // The pending files closest to being done: few refusals, and which ones.
    let mut closest: Vec<(usize, String, String)> = scoreboard
        .pending
        .iter()
        .zip(scoreboard.refusal_sets.iter())
        .map(|(p, c)| {
            let name = p
                .file_name()
                .unwrap_or_default()
                .to_string_lossy()
                .to_string();
            let refusals: Vec<String> = c.iter().map(|r| r.text()).collect();
            (c.len(), name, refusals.join("; "))
        })
        .collect();
    closest.sort();
    println!("  closest to being done:");
    for (n, name, refusals) in closest.iter().take(15) {
        println!("    {n}  {name}: {refusals}");
    }
    // Resolution diagnostics: without this one cannot tell whether injection
    // fails for lack of a shape or because the file is not even in the loaded
    // program.
    let mut outside_program = 0usize;
    let mut unresolved: Vec<String> = Vec::new();
    for p in &scoreboard.pending {
        if resolver.library(p).is_none() {
            outside_program += 1;
            if unresolved.len() < 5 {
                unresolved.push(format!("outside the program: {}", p.display()));
            }
        }
    }
    println!("  pending outside the loaded program: {outside_program}");
    for l in &unresolved {
        println!("    {l}");
    }
    if list {
        for d in divergent.iter() {
            println!("  != {d}");
        }
        for (p, c) in scoreboard.pending.iter().zip(scoreboard.refusal_sets.iter()) {
            let refusals: Vec<String> = c.iter().map(|r| r.text()).collect();
            println!("  .. {} :: {}", p.display(), refusals.join("; "));
        }
    }
    if different == 0 {
        std::process::ExitCode::SUCCESS
    } else {
        std::process::ExitCode::FAILURE
    }
}

/// The load roots: **all** the `.dart` files the generator examines (`lib/`,
/// `web/`, `test/` of the package and the `lib/` of the dependencies), not
/// only those that `main` imports — as `build_runner` resolves each ngdart
/// input. Without this, a component that no page uses stays out of the
/// semantic database, and its `directives:` list does not resolve. The first
/// root is a library (the parts are left to whoever includes them).
///
/// And the hidden ones: the `build_to: source` outputs of phases after the
/// ngdart one, which its resolver does not see (the `x.i18n.dart` of `i18n`,
/// next to the `x.i18n.yaml`), as `Motor::saidas_invisiveis_a` does.
fn all_files(
    root: &std::path::Path,
    dependencies: &[(String, PathBuf)],
) -> (Vec<PathBuf>, std::collections::HashSet<PathBuf>) {
    let mut dirs: Vec<PathBuf> = ["lib", "web", "test"]
        .iter()
        .map(|d| root.join(d))
        .collect();
    dirs.extend(dependencies.iter().map(|(_, d)| d.join("lib")));
    let mut all = Vec::new();
    let mut hidden = std::collections::HashSet::new();
    for dir in dirs {
        let mut stack = vec![dir];
        let mut files = Vec::new();
        while let Some(d) = stack.pop() {
            let Ok(entries) = std::fs::read_dir(&d) else {
                continue;
            };
            for e in entries.flatten() {
                let p = e.path();
                if p.is_dir() {
                    stack.push(p);
                    continue;
                }
                let n = p.to_string_lossy().replace('\\', "/");
                // ngdart's `generate_for` excludes its own compiler.
                let of_compiler = n.contains("/lib/src/compiler/")
                    || n.contains("/lib/src/source_gen/")
                    || n.ends_with("/lib/src/build.dart");
                if !n.ends_with(".dart") || n.ends_with(".template.dart") || of_compiler {
                    continue;
                }
                if let Some(base) = n.strip_suffix(".i18n.dart")
                    && std::path::Path::new(&format!("{base}.i18n.yaml")).is_file()
                {
                    hidden.insert(dartforge_elements::generated::key(&p));
                    continue;
                }
                files.push(p);
            }
        }
        files.sort();
        all.extend(files);
    }
    // The first root must be a library (not `part of`).
    if let Some(i) = all.iter().position(|p| {
        std::fs::read_to_string(p)
            .is_ok_and(|t| !t.lines().any(|l| l.trim_start().starts_with("part of")))
    }) {
        all.swap(0, i);
    }
    (all, hidden)
}

/// Without an SDK there is no name resolution; the scoreboard still holds for
/// the rest.
fn scoreboard_without_resolution(
    _root: &std::path::Path,
    _cfg: &PackageConfig,
    _official: &std::sync::Arc<dartforge_elements::generated::Generation>,
) -> std::process::ExitCode {
    std::process::ExitCode::FAILURE
}
