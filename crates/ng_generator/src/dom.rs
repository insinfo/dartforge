/// `_tagNameToIdentifier`: the `dart:html` class the element is typed with.
/// Outside this table, an HTML tag becomes `HtmlElement` and the rest,
/// `Element`.
const TYPED: &[(&str, &str)] = &[
    ("a", "AnchorElement"),
    ("area", "AreaElement"),
    ("audio", "AudioElement"),
    ("button", "ButtonElement"),
    ("canvas", "CanvasElement"),
    ("div", "DivElement"),
    ("form", "FormElement"),
    ("iframe", "IFrameElement"),
    ("input", "InputElement"),
    ("image", "ImageElement"),
    ("media", "MediaElement"),
    ("menu", "MenuElement"),
    ("ol", "OListElement"),
    ("option", "OptionElement"),
    ("col", "TableColElement"),
    ("row", "TableRowElement"),
    ("select", "SelectElement"),
    ("table", "TableElement"),
    ("textarea", "TextAreaElement"),
    ("ul", "UListElement"),
    ("svg", "SvgSvgElement"),
];

/// Is it an HTML tag name (and not one of an application component)?
pub fn tag_html(name: &str) -> bool {
    TAGS_HTML.contains(&name.to_ascii_lowercase().as_str())
}

/// Type the element is created with (`identifierFromTagName`).
pub fn tag_type(name: &str) -> &'static str {
    let n = name.to_ascii_lowercase();
    if let Some((_, t)) = TYPED.iter().find(|(tag, _)| *tag == n) {
        return t;
    }
    if tag_html(&n) {
        "HtmlElement"
    } else {
        "Element"
    }
}

#[cfg(test)]
mod testes {
    use super::*;

    #[test]
    fn types_as_in_official() {
        // `appendElement<import8.HtmlElement>(doc, _el_0, 'img')` in the
        // no_data_component generated by the official compiler: `img` is not in
        // the typed table, but it is HTML.
        assert_eq!(tag_type("img"), "HtmlElement");
        assert_eq!(tag_type("div"), "DivElement");
        assert_eq!(tag_type("INPUT"), "InputElement");
        assert_eq!(tag_type("meu-componente"), "Element");
        assert!(!tag_html("meu-componente"));
        assert!(tag_html("section"));
    }
}
