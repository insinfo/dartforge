    /// Complete cycle over direct IR, without going through the Dart front end.
    ///
    /// It lives here, and not in `tests/hot_reload.rs`, because it does not need the
    /// compiler: it exercises the mechanism — trampoline, cell, generation — with the
    /// minimum possible IR, and stays valid even if the emitter changes.
    #[test]
    #[ignore = "requires LLVM-C.dll reachable by the loader; use scripts/env.ps1"]
    fn full_cycle_with_direct_ir() {
        let ir = |value: i64| format!("define i64 @df_fn_0() {{\n  ret i64 {value}\n}}\n");
        let mut session = JitSession::new().expect("session");
        let first_one = session
            .add_reloadable_module("app", &ir(1))
            .expect("generation 1");
        assert_eq!(
            (first_one.generation, first_one.entries, first_one.new_entries),
            (1, 1, 1)
        );
        assert_eq!(session.stable_entries("app"), vec!["df_fn_0"]);

        let input = session.stable_entry("df_fn_0").expect("stable entry");
        assert_eq!(input.call(&session).unwrap(), 1);

        let second_one = session.hot_reload("app", &ir(2)).expect("generation 2");
        assert_eq!((second_one.generation, second_one.new_entries), (2, 0));
        assert_eq!(input.call(&session).unwrap(), 2);
        // Generation 1 is no longer reachable: unloaded.
        assert_eq!(session.retained_generations(), 1);

        // Calling an `i64 ()` entry with an argument is an error, not a wrong ABI.
        let error = input.call_with(&session, 7).unwrap_err();
        assert_eq!(error.stage, "lookup");
    }

    #[test]
    #[ignore = "requires the full LLVM distribution"]
    fn eager_stubs_preserve_running_code_and_reuse_zero_slot_orphans_after_failure() {
        let before = "define i64 @df_fn_0() { ret i64 7 }\n";
        let after = "define i64 @df_fn_0() {\n\
            %value = call i64 @df_fn_1()\n\
            %result = add i64 %value, 1\n\
            ret i64 %result\n}\n\
            define i64 @df_fn_1() { ret i64 9 }\n";
        let mut session = JitSession::new().unwrap();
        session.install_generation_with_stubs("app", before, None, StubMaterialization::Eager).unwrap();
        let old = session.stable_entry("df_fn_0").unwrap();
        let old_address = session.lookup("df_fn_0").unwrap();
        assert_eq!(old.call(&session).unwrap(), 7);

        // This failure occurs after the real LLVM stub module has materialized,
        // before any implementation pointer is published or invoked.
        let error = session.install_generation_with_stubs("app", after, None, StubMaterialization::FailAfterEager).unwrap_err();
        assert_eq!(error.stage, "link");
        assert!(error.message.contains("injected failure"));
        assert_eq!(session.generation("app"), Some(1));
        assert_eq!(session.lookup("df_fn_0").unwrap(), old_address);
        assert_eq!(old.call(&session).unwrap(), 7);
        assert!(session.stable_entry("df_fn_1").unwrap_err().message.contains("no generation implemented"));
        let orphan = &session.reloadables[0].entries["df_fn_1"];
        assert_eq!(orphan.generation, 0);
        assert_eq!(orphan.slot.load(std::sync::atomic::Ordering::Acquire), 0);
        let orphan_address = session.lookup("df_fn_1").unwrap();

        session.install_generation_with_stubs("app", after, None, StubMaterialization::Eager).unwrap();
        assert_eq!(session.generation("app"), Some(2));
        assert_eq!(session.lookup("df_fn_0").unwrap(), old_address);
        assert_eq!(session.lookup("df_fn_1").unwrap(), orphan_address);
        assert_eq!(old.call(&session).unwrap(), 10);
        assert_eq!(session.stable_entry("df_fn_1").unwrap().call(&session).unwrap(), 9);
    }

    /// Promotion: a simple module gets trampolines on the first reload.
    ///
    /// Before promotion there is no stable entry, and an address obtained from the simple
    /// version is the body's — that is why promotion is the only destructive operation
    /// of hot reload, and why it is measured and reported in `promoted`.
    #[test]
    #[ignore = "requires LLVM-C.dll reachable by the loader; use scripts/env.ps1"]
    fn simple_module_promotion() {
        let ir = |value: i64| format!("define i64 @df_fn_0() {{\n  ret i64 {value}\n}}\n");
        let mut session = JitSession::new().expect("session");
        session.add_ir_module("app", &ir(1)).expect("simple module");
        assert!(session.stable_entry("df_fn_0").is_err());

        let report_data = session.hot_reload("app", &ir(2)).expect("promotion");
        assert!(report_data.promoted);
        assert_eq!((report_data.generation, report_data.new_entries), (1, 1));
        assert_eq!(session.module_names(), vec!["app"]);

        let input = session.stable_entry("df_fn_0").expect("stable entry");
        assert_eq!(input.call(&session).unwrap(), 2);
        // From the second reload on there is nothing destructive left to do.
        let report_data = session.hot_reload("app", &ir(3)).expect("generation 2");
        assert!(!report_data.promoted);
        assert_eq!(input.call(&session).unwrap(), 3);
    }

    /// The contract checked during promotion uses the simple module's fingerprint.
    #[test]
    #[ignore = "requires LLVM-C.dll reachable by the loader; use scripts/env.ps1"]
    fn promotion_rejects_incompatible_contract_without_destroying_anything() {
        let mut session = JitSession::new().expect("session");
        session
            .add_ir_module("app", "define i64 @df_fn_0() {\n  ret i64 1\n}\n")
            .expect("simple module");
        let error = session
            .hot_reload("app", "define i64 @df_fn_0(i64 %a0) {\n  ret i64 %a0\n}\n")
            .expect_err("a changed signature must be refused");
        assert_eq!(error.stage, "contract");
        // The simple module stays loaded: the refusal comes before the promotion.
        assert_eq!(
            session.lookup("df_fn_0").map(|address| address != 0),
            Ok(true)
        );
        assert_eq!(session.retained_generations(), 0);
    }

