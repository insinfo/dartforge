//! Behaviour hot reload: stable identity, per-generation implementation.
//!
//! The design is that of increment 28 of `PLANO.md`, and the central piece is the separation
//! between **who** a function is and **what it does now**:
//!
//! * the **stable entry** is a trampoline that is never unloaded. It carries the
//!   name the emitter produced (`dartforge_entry`, `df_fn_0`, `df_method_0_0`)
//!   and is the only address that leaves the session;
//! * the **implementation** is versioned per generation (`df_fn_0$gen3`) and lives under its own
//!   `ResourceTracker`;
//! * the link between the two is a **pointer cell** owned by Rust,
//!   published in the `JITDylib` as an absolute data symbol. The trampoline reads that
//!   cell on every call; reloading is swapping its content.
//!
//! ```text
//!   caller  ──►  @df_fn_0            (trampoline, permanent)
//!                    │ load  @__dfslot$df_fn_0
//!                    ▼
//!                  cell ──► @df_fn_0$gen1   (generation 1, retained)
//!                       └─► @df_fn_0$gen2   (generation 2, published)
//! ```
//!
//! # Why not `LLVMOrcCreateLocalIndirectStubsManager`
//!
//! `PLANO.md` points to `LLVMOrcCreateLocalIndirectStubsManager` and
//! `LLVMOrcCreateLocalLazyCallThroughManager` as the ready-made primitives for
//! this, and `llvm-sys 221.1.0` **exposes both**. They do not work, and the reason is
//! verifiable in the very list of symbols `llvm-sys` publishes: of the class
//! `IndirectStubsManager` the C API exports only
//! `LLVMOrcCreateLocalIndirectStubsManager` and
//! `LLVMOrcDisposeIndirectStubsManager`. There is no C entry for `createStub` nor
//! for **`updatePointer`**, which is exactly the operation of a reload: pointing
//! an existing stub to another implementation. The only exposed consumer is
//! `LLVMOrcLazyReexports`, which returns a materialization unit of *lazy
//! aliases*: the stub is created on the first call, resolved once and the
//! pointer holds forever. Redefining the same alias in a second
//! generation is not possible — the name is already defined in the `JITDylib`, and a duplicate
//! definition is an error.
//!
//! What was left is the path the plan itself foresees as an alternative: a **table of
//! mutable pointers with an indirect jump**. Here it is not hand-written
//! assembly, but IR generated by the session itself — the trampoline is an LLVM function of
//! three instructions (`load`, `call`, `ret`), and therefore holds on any target
//! LLVM supports, without one emitter per architecture.
//!
//! The cost is one `load` and one stack frame per call of a reloadable function.
//! It does not exist on the non-reloadable path ([`JitSession::add_ir_module`]),
//! nor in the AOT.
//!
//! # Generations and `JITDylib`
//!
//! `PLANO.md` asks for «its own `JITDylib`/tracker» per reload. The tracker is
//! indeed its own. The `JITDylib` is **not**: the C API creates dylibs
//! (`LLVMOrcExecutionSessionCreateJITDylib`) but exposes no
//! `SetLinkOrder`, so a new dylib is born without a link order and would not
//! reach the runtime symbols nor the trampolines — the generation's code
//! would not link. The name separation a dylib would give is obtained through the generation
//! suffix, and per-generation unloading belongs to the `ResourceTracker`, which is what
//! LLVM offers for that.
//!
//! # Memory retention
//!
//! A generation is unloaded at the next publication, when no stable
//! entry reaches it anymore (J02). See [`JitSession::hot_reload`].

