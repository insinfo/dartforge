//! Pub-compatible lockfile and package configuration generation.
use super::{
    hosted::atomic_write,
    manifest::{Manifest, Source, yaml_json},
    resolver::Selected,
};
use semver::Version;
use serde_json::json;
use std::{collections::BTreeMap, path::Path};

pub(super) fn read_lock(
    directory: &Path,
    host: &str,
) -> Result<BTreeMap<String, (Source, Version)>, String> {
    let path = directory.join("pubspec.lock");
    if !path.exists() {
        return Ok(BTreeMap::new());
    }
    let value = yaml_json(&std::fs::read_to_string(path).map_err(|e| e.to_string())?)?;
    let mut result = BTreeMap::new();
    let packages = value["packages"]
        .as_object()
        .ok_or("pubspec.lock packages must be a mapping")?;
    for (name, p) in packages {
        let version = Version::parse(p["version"].as_str().ok_or("lockfile version is missing")?)
            .map_err(|e| e.to_string())?;
        let source = match p["source"].as_str() {
            Some("path") => {
                let path = p["description"]["path"]
                    .as_str()
                    .ok_or("lockfile path is missing")?;
                let path = directory
                    .join(path)
                    .canonicalize()
                    .map_err(|e| e.to_string())?;
                Source::Path(path)
            }
            Some("hosted") => Source::Hosted(super::hosted::normalize_host(
                p["description"]["url"].as_str().unwrap_or(host),
            )?),
            _ => return Err(format!("unsupported locked source for {name}")),
        };
        result.insert(name.clone(), (source, version));
    }
    Ok(result)
}
fn quote(text: &str) -> String {
    serde_json::to_string(text).expect("string serialization")
}
pub(super) fn write(
    directory: &Path,
    root: &Manifest,
    selected: &BTreeMap<String, Selected>,
    sdk: &Version,
) -> Result<(), String> {
    let mut lock = String::from("# Generated by dartforge pub get.\npackages:\n");
    if selected.is_empty() {
        lock.push_str("  {}\n");
    }
    let mut packages = Vec::new();
    for (name, value) in selected {
        let kind = if root.overrides.contains_key(name) {
            "direct overridden"
        } else if root.dependencies.contains_key(name) {
            "direct main"
        } else if root.dev.contains_key(name) {
            "direct dev"
        } else {
            "transitive"
        };
        lock.push_str(&format!(
            "  {name}:\n    dependency: {}\n    description:\n",
            quote(kind)
        ));
        match &value.source {
            Source::Path(path) => lock.push_str(&format!(
                "      path: {}\n      relative: false\n    source: path\n",
                quote(&path.to_string_lossy())
            )),
            Source::Hosted(host) => lock.push_str(&format!(
                "      name: {}\n      sha256: {}\n      url: {}\n    source: hosted\n",
                quote(name),
                quote(
                    value
                        .candidate
                        .digest
                        .as_deref()
                        .ok_or("missing archive hash")?
                ),
                quote(host)
            )),
        }
        lock.push_str(&format!(
            "    version: {}\n",
            quote(&value.candidate.manifest.version.to_string())
        ));
        packages.push(config_package(
            name,
            &value.candidate.directory,
            &value.candidate.manifest,
            sdk,
        )?);
    }
    let mut lower = None;
    let mut upper = None;
    for manifest in std::iter::once(root).chain(
        selected
            .values()
            .filter(|v| !root.overrides.contains_key(&v.candidate.manifest.name))
            .map(|v| &v.candidate.manifest),
    ) {
        let constraint = manifest.sdk.for_sdk(sdk);
        if let Some(bound) = constraint.lower {
            if lower.as_ref().is_none_or(|(v, inc): &(Version, bool)| {
                super::constraints::compare_versions(&bound.0, v).is_gt()
                    || (super::constraints::compare_versions(&bound.0, v).is_eq()
                        && !bound.1
                        && *inc)
            }) {
                lower = Some(bound);
            }
        }
        if let Some(bound) = constraint.upper {
            if upper.as_ref().is_none_or(|(v, inc): &(Version, bool)| {
                super::constraints::compare_versions(&bound.0, v).is_lt()
                    || (super::constraints::compare_versions(&bound.0, v).is_eq()
                        && !bound.1
                        && *inc)
            }) {
                upper = Some(bound);
            }
        }
    }
    let mut sdk_parts = Vec::new();
    if let Some((v, inc)) = lower {
        sdk_parts.push(format!("{}{v}", if inc { ">=" } else { ">" }));
    }
    if let Some((v, inc)) = upper {
        sdk_parts.push(format!("{}{v}", if inc { "<=" } else { "<" }));
    }
    lock.push_str(&format!("sdks:\n  dart: {}\n", quote(&sdk_parts.join(" "))));
    packages.push(config_package(&root.name, directory, root, sdk)?);
    packages.sort_by(|a, b| a["name"].as_str().cmp(&b["name"].as_str()));
    let config = json!({"configVersion":2,"packages":packages,"generator":"dartforge","generatorVersion":env!("CARGO_PKG_VERSION")});
    let bytes = serde_json::to_vec_pretty(&config).map_err(|e| e.to_string())?;
    atomic_write(&directory.join("pubspec.lock"), lock.as_bytes())?;
    atomic_write(&directory.join(".dart_tool/package_config.json"), &bytes)
}
fn config_package(
    name: &str,
    directory: &Path,
    manifest: &Manifest,
    sdk: &Version,
) -> Result<serde_json::Value, String> {
    let uri = url::Url::from_directory_path(directory)
        .map_err(|_| format!("invalid package directory {}", directory.display()))?;
    Ok(
        json!({"name":name,"rootUri":uri.as_str(),"packageUri":"lib/","languageVersion":manifest.sdk.language(sdk)}),
    )
}
