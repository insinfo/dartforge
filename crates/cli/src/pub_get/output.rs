//! `pubspec.lock`, `.dart_tool/package_config.json` and
//! `workspace_ref.json` as Pub 3.6.2 writes them.
use super::{
    hosted::atomic_write,
    manifest::{Description, Manifest},
    solver::WorkspacePackage,
    source::{Cache, PackageId},
    version::VersionSet,
};
use std::{
    collections::{BTreeMap, HashSet},
    path::Path,
};

/// The lockfile a resolution produces.
#[derive(Clone, Debug)]
pub(crate) struct NewLock {
    pub packages: BTreeMap<String, PackageId>,
    /// The intersection of the SDK constraints of the resolved packages, by
    /// SDK name.
    pub sdks: BTreeMap<String, VersionSet>,
    pub main: HashSet<String>,
    pub dev: HashSet<String>,
    pub overridden: HashSet<String>,
}

impl NewLock {
    /// `LockFile._dependencyType`.
    pub fn kind(&self, name: &str) -> &'static str {
        if self.main.contains(name) {
            "direct main"
        } else if self.dev.contains(name) {
            "direct dev"
        } else if self.overridden.contains(name) {
            "direct overridden"
        } else {
            "transitive"
        }
    }
}

/// Pub's `yamlToString` scalars: identifier-like strings stay plain,
/// everything else is written as a JSON string.
pub(crate) fn quote(text: &str) -> String {
    let mut bytes = text.bytes();
    let plain = bytes
        .next()
        .is_some_and(|b| b.is_ascii_alphabetic() || b == b'_' || b == b'-')
        && bytes.all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-');
    if plain {
        text.to_owned()
    } else {
        serde_json::to_string(text).expect("string serialization")
    }
}

/// `path` relative to `base` with `/` separators (Pub's `p.relative` on
/// POSIX); both are absolute and normalized.
pub(crate) fn relative_path(path: &Path, base: &Path) -> String {
    let path: Vec<_> = path.components().collect();
    let base: Vec<_> = base.components().collect();
    let shared = path.iter().zip(&base).take_while(|(a, b)| a == b).count();
    let mut parts = vec!["..".to_string(); base.len() - shared];
    parts.extend(
        path[shared..]
            .iter()
            .map(|c| c.as_os_str().to_string_lossy().into_owned()),
    );
    if parts.is_empty() {
        ".".into()
    } else {
        parts.join("/")
    }
}

/// `p.toUri` of a relative path: segments are percent-encoded and a final
/// `..` segment gains a slash, as Dart's URI normalization does.
fn relative_uri(path: &str) -> String {
    let mut uri = String::new();
    for byte in path.bytes() {
        // RFC 3986 path characters stay as they are, like Dart's `Uri`.
        if byte.is_ascii_alphanumeric() || b"-._~!$&'()*+,;=:@/".contains(&byte) {
            uri.push(byte as char);
        } else {
            uri.push_str(&format!("%{byte:02X}"));
        }
    }
    if path == ".." || path.ends_with("/..") {
        uri.push('/');
    }
    uri
}

fn file_uri(directory: &Path) -> Result<String, String> {
    url::Url::from_file_path(directory)
        .map(|u| u.to_string())
        .map_err(|_| format!("invalid package directory {}", directory.display()))
}

/// `p.url.relative(url, from: dir)` for a `file:` URL of a relative local
/// Git repository.
fn relative_git_url(url: &str, directory: &Path) -> String {
    match url::Url::parse(url)
        .ok()
        .and_then(|u| u.to_file_path().ok())
    {
        Some(path) => relative_path(&path, directory),
        None => url.to_owned(),
    }
}

/// The text of `pubspec.lock` for `lock`, written in `directory`.
pub(crate) fn lock_text(lock: &NewLock, directory: &Path) -> Result<String, String> {
    let mut text =
        String::from("# Generated by pub\n# See https://dart.dev/tools/pub/glossary#lockfile\n");
    text.push_str(if lock.packages.is_empty() {
        "packages: {}\n"
    } else {
        "packages:\n"
    });
    for (name, id) in &lock.packages {
        text.push_str(&format!(
            "  {}:\n    dependency: {}\n",
            quote(name),
            quote(lock.kind(name))
        ));
        match &id.description {
            Description::Path { path, relative } => {
                if *relative {
                    text.push_str(&format!(
                        "    description:\n      path: {}\n      relative: true\n",
                        quote(&relative_path(path, directory))
                    ));
                } else {
                    text.push_str(&format!(
                        "    description:\n      path: {}\n      relative: false\n",
                        quote(&path.to_string_lossy())
                    ));
                }
            }
            Description::Hosted(url) => {
                text.push_str(&format!("    description:\n      name: {}\n", quote(name)));
                if let Some(hash) = &id.resolved {
                    text.push_str(&format!("      sha256: {}\n", quote(hash)));
                }
                text.push_str(&format!("      url: {}\n", quote(url)));
            }
            Description::Git {
                url,
                relative,
                reference,
                path,
            } => {
                let commit = id
                    .resolved
                    .as_deref()
                    .ok_or("missing resolved git commit")?;
                let url = if *relative {
                    relative_git_url(url, directory)
                } else {
                    url.clone()
                };
                text.push_str(&format!(
                    "    description:\n      path: {}\n      ref: {}\n      resolved-ref: {}\n      url: {}\n",
                    quote(path),
                    quote(reference),
                    quote(commit),
                    quote(&url)
                ));
            }
            Description::Sdk(sdk) => {
                text.push_str(&format!("    description: {}\n", quote(sdk)));
            }
            Description::Root(_) | Description::Unknown { .. } => {
                return Err(format!("{name}: cannot be written to the lockfile"));
            }
        }
        text.push_str(&format!(
            "    source: {}\n    version: {}\n",
            quote(id.description.source()),
            quote(&id.version.to_string())
        ));
    }
    text.push_str("sdks:\n");
    for (sdk, constraint) in &lock.sdks {
        text.push_str(&format!(
            "  {}: {}\n",
            quote(sdk),
            quote(&constraint.to_string())
        ));
    }
    Ok(text)
}

/// Writes `pubspec.lock` unless an equal text is already there; keeps
/// Windows line endings of an existing file, like Pub.
pub(crate) fn write_lock(lock: &NewLock, directory: &Path) -> Result<(), String> {
    let path = directory.join("pubspec.lock");
    let mut text = lock_text(lock, directory)?;
    if let Ok(existing) = std::fs::read_to_string(&path) {
        if existing.contains("\r\n") {
            text = text.replace('\n', "\r\n");
        }
        if existing == text {
            return Ok(());
        }
    }
    atomic_write(&path, text.as_bytes())
}

fn language(manifest: &Manifest) -> String {
    let (major, minor) = manifest.language_version();
    format!("{major}.{minor}")
}

/// Dart's `DateTime.now().toUtc().toIso8601String()`.
fn now_iso8601() -> String {
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default();
    let seconds = now.as_secs() as i64;
    let micros = now.subsec_micros();
    let days = seconds.div_euclid(86_400);
    let rest = seconds.rem_euclid(86_400);
    // Howard Hinnant's civil-from-days.
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    let mut text = format!(
        "{year:04}-{month:02}-{day:02}T{:02}:{:02}:{:02}.{:03}",
        rest / 3600,
        rest % 3600 / 60,
        rest % 60,
        micros / 1000
    );
    if !micros.is_multiple_of(1000) {
        text.push_str(&format!("{:03}", micros % 1000));
    }
    text.push('Z');
    text
}

/// Writes `.dart_tool/package_config.json` at the workspace root and, for
/// a workspace, the `workspace_ref.json` of every member.
pub(crate) fn write_package_config(
    workspace: &[WorkspacePackage],
    lock: &NewLock,
    cache: &mut Cache,
) -> Result<(), String> {
    let root = &workspace[0].directory;
    let tool = root.join(".dart_tool");
    let mut entries: Vec<(String, String, String)> = Vec::new();
    for (name, id) in &lock.packages {
        let directory = cache.directory(id)?;
        let uri = match &id.description {
            Description::Path { relative: true, .. } => {
                relative_uri(&relative_path(&directory, &tool))
            }
            Description::Git { path, .. } => {
                let uri = file_uri(&directory)?;
                // `p.join(checkout, '.')` becomes a URI with a final slash.
                if path == "." { format!("{uri}/") } else { uri }
            }
            _ => file_uri(&directory)?,
        };
        let manifest = cache.describe(id).map_err(|e| match e {
            super::source::SourceError::NotFound(m)
            | super::source::SourceError::Invalid(m)
            | super::source::SourceError::Fatal(m) => m,
        })?;
        entries.push((name.clone(), uri, language(&manifest)));
    }
    for package in workspace {
        entries.push((
            package.manifest.name.clone(),
            relative_uri(&relative_path(&package.directory, &tool)),
            language(&package.manifest),
        ));
    }
    let string = |s: &str| serde_json::to_string(s).expect("string serialization");
    let mut config = String::from("{\n  \"configVersion\": 2,\n  \"packages\": [\n");
    for (index, (name, uri, language)) in entries.iter().enumerate() {
        config.push_str(&format!(
            "    {{\n      \"name\": {},\n      \"rootUri\": {},\n      \"packageUri\": \"lib/\",\n      \"languageVersion\": {}\n    }}{}\n",
            string(name),
            string(uri),
            string(language),
            if index + 1 < entries.len() { "," } else { "" }
        ));
    }
    let cache_uri = file_uri(&cache.root)?;
    config.push_str(&format!(
        "  ],\n  \"generated\": {},\n  \"generator\": \"pub\",\n  \"generatorVersion\": {},\n  \"pubCache\": {}\n}}\n",
        string(&now_iso8601()),
        string(&cache.sdk.to_string()),
        string(cache_uri.trim_end_matches('/'))
    ));
    if entries.is_empty() {
        config = config.replace("\"packages\": [\n  ]", "\"packages\": []");
    }
    atomic_write(&tool.join("package_config.json"), config.as_bytes())?;
    if workspace[0].children.is_empty() {
        return Ok(());
    }
    for package in workspace {
        let reference = relative_path(root, &package.directory.join(".dart_tool/pub"));
        let text = format!("{{\n  \"workspaceRoot\": {}\n}}\n", string(&reference));
        atomic_write(
            &package.directory.join(".dart_tool/pub/workspace_ref.json"),
            text.as_bytes(),
        )?;
    }
    Ok(())
}

/// Pub's `_removeStrayLockAndConfigFiles`: workspace members keep no
/// resolution files of their own.
pub(crate) fn remove_stray_files(workspace: &[WorkspacePackage]) -> Result<(), String> {
    for package in workspace.iter().skip(1) {
        for (stray, what) in [
            ("pubspec.lock", "lock-file"),
            (".dart_tool/package_config.json", "package config"),
        ] {
            let path = package.directory.join(stray);
            if path.is_file() {
                std::fs::remove_file(&path).map_err(|e| format!("{}: {e}", path.display()))?;
                eprintln!("Deleting old {what}: `{}/{stray}`.", package.shown);
            }
        }
    }
    Ok(())
}
