//! `dartforge pack <destination>`: assembles the dartforge distribution —
//! the executable and everything it needs at run time, in the layout of
//! `dartforge_elements::distribution` — from the development tree that built
//! this binary. Whoever receives the distribution does not install Rust,
//! LLVM or the Dart SDK.
//!
//! ```text
//! bin/dartforge[.exe]            this executable (and the JIT's LLVM-C.dll on Windows)
//! bin/dartforge-lsp[.exe]        the language server, when built next to this executable
//! lib/dartforge-distribution.json
//! lib/runtime/                   the two runtime staticlibs (emit_native's build.rs)
//! lib/native_sdk/                the native backend overlay
//! lib/dart-sdk/{lib,version}     the Dart SDK libraries
//! lib/llvm/bin/                  lld (and Clang, if the build has no embedded generator)
//! lib/sysroot/<triple>/          what linking requires from the system: on Linux, glibc and
//!                                libgcc; on Windows, the import libraries and dartforge's
//!                                minimal CRT; on macOS, the generated `.tbd` files
//! ```
use std::path::{Path, PathBuf};

type Outcome = Result<(), Box<dyn std::error::Error>>;

pub fn run(args: &[std::ffi::OsString]) -> Outcome {
    let [destination] = args else {
        return Err("usage: dartforge pack <destination>".into());
    };
    let destination = PathBuf::from(destination);
    if destination.exists() && std::fs::read_dir(&destination)?.next().is_some() {
        return Err(format!("{} already exists and is not empty", destination.display()).into());
    }
    let bin = destination.join("bin");
    let lib = destination.join("lib");
    std::fs::create_dir_all(&bin)?;
    std::fs::create_dir_all(lib.join("runtime"))?;
    std::fs::create_dir_all(lib.join("llvm").join("bin"))?;

    // The executable.
    let exe = std::env::current_exe()?;
    copy(
        &exe,
        &bin.join(exe.file_name().ok_or("executable without a name")?),
    )?;

    // The language server, when it was built next to this executable
    // (`cargo build --release -p dartforge-lsp`): in `bin/`, it finds the
    // distribution's Dart SDK by itself.
    let server = if cfg!(windows) {
        "dartforge-lsp.exe"
    } else {
        "dartforge-lsp"
    };
    if let Some(sibling) = exe.parent().map(|d| d.join(server))
        && sibling.is_file()
    {
        copy(&sibling, &bin.join(server))?;
    }

    // The precompiled runtime (the three variants).
    for r in [
        dartforge_emit_native::cache::RuntimeCache::get_or_compile()?,
        dartforge_emit_native::cache::RuntimeCache::for_dll()?,
        dartforge_emit_native::cache::RuntimeCache::for_production()?,
    ] {
        copy(
            &r.lib_path,
            &lib.join("runtime")
                .join(r.lib_path.file_name().ok_or("runtime without a name")?),
        )?;
    }

    // The overlay and the Dart SDK.
    copy_tree(
        &dartforge_emit_native::sdk_module::overlay_dir(),
        &lib.join("native_sdk"),
    )?;
    let sdk = dartforge_emit_native::dart_sdk()?;
    copy_tree(&sdk, &lib.join("dart-sdk").join("lib"))?;
    if let Some(root) = sdk.parent() {
        if root.join("version").is_file() {
            copy(&root.join("version"), &lib.join("dart-sdk").join("version"))?;
        }
        copy_sdk_packages(root, &lib.join("dart-sdk"))?;
    }

    // The target system's lld (from the same LLVM as the generator) and what
    // linking requires from the system, which is not asked of dartforge's
    // users: on Linux, this machine's glibc and libgcc; on Windows, the import
    // libraries and the minimal CRT generated by dartforge (nothing from MSVC
    // or the Windows SDK); on macOS, the `.tbd` files generated by dartforge
    // (nothing from Apple's SDK). Clang only ships when this build has no
    // embedded generator (it is what compiles the IR).
    let clang = dartforge_emit_native::driver::NativeDriverOptions::default().clang;
    let clang = locate(&clang).ok_or_else(|| format!("Clang not found ({})", clang.display()))?;
    let llvm_dir = clang
        .parent()
        .ok_or("Clang without a directory")?
        .to_path_buf();
    let llvm_bin = lib.join("llvm").join("bin");
    use dartforge_emit_native::target::{Os, target_os};
    match target_os() {
        Os::Linux => {
            let sysroot = dartforge_emit_native::linker::SysrootLinux::from_system(&clang)?;
            sysroot.copy_to(
                &lib.join("sysroot")
                    .join(dartforge_emit_native::linker::sysroot_triple()),
            )?;
        }
        Os::Windows => {
            use dartforge_emit_native::linker_windows as lw;
            let generator = dartforge_emit_native::generator::Generator::choose(&clang);
            lw::generate(
                &lib.join("sysroot").join(lw::TRIPLE),
                &lw::CrtCompiler::Generator(&generator),
            )?;
        }
        Os::MacOs => {
            use dartforge_emit_native::linker_macos as lm;
            let arch = lm::Arch::host();
            lm::generate(&lib.join("sysroot").join(arch.sysroot_triple()), arch)?;
        }
        Os::Wasm => unreachable!("pack describes a native compiler host"),
    }
    if !dartforge_emit_native::generator::EMBEDDED_GENERATOR {
        copy(
            &clang,
            &llvm_bin.join(dartforge_emit_native::target::clang_name()),
        )?;
    }
    let lld = if cfg!(windows) {
        "lld-link.exe"
    } else if cfg!(target_os = "macos") {
        "ld64.lld"
    } else {
        "ld.lld"
    };
    copy(&llvm_dir.join(lld), &llvm_bin.join(lld))?;
    // The executables of the official LLVM package come with the symbol table
    // (Linux's `ld.lld`: 200 MB → 1/3 of that without it).
    let strip = llvm_dir.join(if cfg!(windows) {
        "llvm-strip.exe"
    } else {
        "llvm-strip"
    });
    if strip.is_file() {
        let mut executables: Vec<PathBuf> = std::fs::read_dir(&llvm_bin)?
            .flatten()
            .map(|e| e.path())
            .collect();
        if !cfg!(windows) {
            // On Windows the symbols are already kept apart, in the PDB.
            executables.push(bin.join(exe.file_name().ok_or("executable without a name")?));
        }
        for e in executables {
            let st = std::process::Command::new(&strip)
                .arg("--strip-all")
                .arg(&e)
                .status()?;
            if !st.success() {
                return Err(format!("llvm-strip failed on {}", e.display()).into());
            }
        }
    }
    // The JIT on Windows loads the LLVM C API DLL next to the executable.
    if cfg!(windows) && llvm_dir.join("LLVM-C.dll").is_file() {
        copy(&llvm_dir.join("LLVM-C.dll"), &bin.join("LLVM-C.dll"))?;
    }

    // The marker file; its keys are a serialized format and stay as they are.
    let marker = format!(
        "{{\n  \"versao\": \"{}\",\n  \"alvo\": \"{}-{}\",\n  \"sdk_do_dart\": \"{}\"\n}}\n",
        env!("CARGO_PKG_VERSION"),
        std::env::consts::ARCH,
        std::env::consts::OS,
        std::fs::read_to_string(lib.join("dart-sdk").join("version"))
            .unwrap_or_default()
            .trim(),
    );
    std::fs::write(lib.join(dartforge_elements::distribution::MARKER), marker)?;
    println!("distribution in {}", destination.display());
    Ok(())
}

/// The real path of an executable: as given, or through `PATH`; symbolic
/// links resolved (the `clang` of the LLVM package points to `clang-22`).
fn locate(p: &Path) -> Option<PathBuf> {
    let found = if p.components().count() > 1 {
        p.is_file().then(|| p.to_path_buf())
    } else {
        std::env::split_paths(&std::env::var_os("PATH")?)
            .map(|d| d.join(p))
            .find(|c| c.is_file())
    }?;
    Some(found.canonicalize().unwrap_or(found))
}

/// Copies a file, following symbolic links, with its permissions.
fn copy(from: &Path, to: &Path) -> Result<(), String> {
    std::fs::copy(from, to)
        .map(|_| ())
        .map_err(|e| format!("copy {} → {}: {e}", from.display(), to.display()))
}

fn copy_tree(from: &Path, to: &Path) -> Result<(), String> {
    std::fs::create_dir_all(to).map_err(|e| format!("{}: {e}", to.display()))?;
    let entries = std::fs::read_dir(from).map_err(|e| format!("{}: {e}", from.display()))?;
    for e in entries.flatten() {
        let path = e.path();
        let target = to.join(e.file_name());
        if path.is_dir() {
            copy_tree(&path, &target)?;
        } else {
            copy(&path, &target)?;
        }
    }
    Ok(())
}

/// Retains the selected SDK's declared package locations after relocation.
fn copy_sdk_packages(source: &Path, destination: &Path) -> Result<(), String> {
    let config = source.join("sdk_packages.yaml");
    match std::fs::symlink_metadata(&config) {
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(format!("{}: {error}", config.display())),
        Ok(_) => {}
    }
    let root = source
        .canonicalize()
        .map_err(|error| format!("{}: {error}", source.display()))?;
    let packages = crate::pub_get::sdk_package_paths(source)?;
    for (name, relative) in packages {
        let package = source.join(&relative);
        if !package.is_dir() {
            return Err(format!(
                "declared SDK package {name} is not a directory: {}",
                package.display()
            ));
        }
        copy_sdk_tree(
            &package,
            &destination.join(relative),
            &root,
            &mut std::collections::HashSet::new(),
        )?;
    }
    copy_sdk_tree(
        &config,
        &destination.join("sdk_packages.yaml"),
        &root,
        &mut std::collections::HashSet::new(),
    )
}

fn copy_sdk_tree(
    source: &Path,
    destination: &Path,
    root: &Path,
    active: &mut std::collections::HashSet<PathBuf>,
) -> Result<(), String> {
    let canonical = source
        .canonicalize()
        .map_err(|error| format!("{}: {error}", source.display()))?;
    if !canonical.starts_with(root) {
        return Err(format!(
            "SDK package path escapes the selected SDK: {}",
            source.display()
        ));
    }
    if !canonical.is_dir() {
        if let Some(parent) = destination.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|error| format!("{}: {error}", parent.display()))?;
        }
        return copy(source, destination);
    }
    if !active.insert(canonical.clone()) {
        return Err(format!(
            "cyclic SDK package directory: {}",
            source.display()
        ));
    }
    std::fs::create_dir_all(destination)
        .map_err(|error| format!("{}: {error}", destination.display()))?;
    for entry in
        std::fs::read_dir(source).map_err(|error| format!("{}: {error}", source.display()))?
    {
        let entry = entry.map_err(|error| format!("{}: {error}", source.display()))?;
        copy_sdk_tree(
            &entry.path(),
            &destination.join(entry.file_name()),
            root,
            active,
        )?;
    }
    active.remove(&canonical);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    struct Fixture(PathBuf);
    impl Fixture {
        fn new() -> Self {
            static NEXT: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
            let path = std::env::temp_dir().join(format!(
                "dartforge-pack-sdk-{}-{}",
                std::process::id(),
                NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
            ));
            std::fs::create_dir_all(&path).unwrap();
            Self(path)
        }
        fn sdk(&self, mapping: &str) -> PathBuf {
            let sdk = self.0.join("source-sdk");
            std::fs::create_dir_all(&sdk).unwrap();
            std::fs::write(sdk.join("sdk_packages.yaml"), mapping).unwrap();
            sdk
        }
        fn package(&self, sdk: &Path, relative: &str, name: &str) {
            let path = sdk.join(relative);
            std::fs::create_dir_all(path.join("lib")).unwrap();
            std::fs::write(
                path.join("pubspec.yaml"),
                format!("name: {name}\nversion: 1.2.3\n"),
            )
            .unwrap();
            std::fs::write(path.join("lib/value.dart"), "const value = 37;\n").unwrap();
        }
    }
    impl Drop for Fixture {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    #[test]
    fn declared_sdk_packages_keep_metadata_and_arbitrary_paths_after_relocation() {
        let fixture = Fixture::new();
        let mapping = "version: 1\nsdk: dart\npackages:\n  - name: one\n    path: vendored/first\n  - name: two\n    path: elsewhere/second\n";
        let source = fixture.sdk(mapping);
        fixture.package(&source, "vendored/first", "one");
        fixture.package(&source, "elsewhere/second", "two");
        let destination = fixture.0.join("relocated-sdk");
        copy_sdk_packages(&source, &destination).unwrap();
        assert_eq!(
            std::fs::read(destination.join("sdk_packages.yaml")).unwrap(),
            mapping.as_bytes()
        );
        assert_eq!(
            crate::pub_get::sdk_package_paths(&source).unwrap(),
            crate::pub_get::sdk_package_paths(&destination).unwrap()
        );
        for path in ["vendored/first", "elsewhere/second"] {
            for file in ["pubspec.yaml", "lib/value.dart"] {
                assert_eq!(
                    std::fs::read(source.join(path).join(file)).unwrap(),
                    std::fs::read(destination.join(path).join(file)).unwrap()
                );
            }
        }
        std::fs::remove_dir_all(source).unwrap();
        assert!(destination.join("vendored/first/lib/value.dart").is_file());
    }

    #[test]
    fn declared_sdk_packages_reject_nonrelative_and_traversing_paths() {
        for path in [
            "../outside",
            "/outside",
            ".",
            "pkg/../../outside",
            "pkg\\outside",
            "C:/outside",
            "C:outside",
        ] {
            let fixture = Fixture::new();
            let source = fixture.sdk(&format!(
                "version: 1\nsdk: dart\npackages:\n  - name: one\n    path: '{path}'\n"
            ));
            assert!(
                copy_sdk_packages(&source, &fixture.0.join("packed"))
                    .unwrap_err()
                    .contains("relative path without traversal"),
                "{path}"
            );
        }
    }

    #[test]
    fn declared_sdk_packages_reject_missing_duplicate_and_malformed_declarations() {
        for (mapping, expected) in [
            (
                "version: 1\nsdk: dart\npackages:\n  - name: one\n    path: absent\n",
                "not a directory",
            ),
            (
                "version: 1\nsdk: dart\npackages:\n  - name: one\n    path: first\n  - name: one\n    path: second\n",
                "duplicate declared",
            ),
            (
                "version: 2\nsdk: dart\npackages: []\n",
                "unsupported selected",
            ),
        ] {
            let fixture = Fixture::new();
            let source = fixture.sdk(mapping);
            assert!(
                copy_sdk_packages(&source, &fixture.0.join("packed"))
                    .unwrap_err()
                    .contains(expected)
            );
        }
    }

    #[test]
    fn sdk_without_declared_packages_keeps_optional_metadata_absent() {
        let fixture = Fixture::new();
        let source = fixture.0.join("old-sdk");
        std::fs::create_dir_all(&source).unwrap();
        let destination = fixture.0.join("packed");
        copy_sdk_packages(&source, &destination).unwrap();
        assert!(!destination.join("sdk_packages.yaml").exists());
    }

    #[cfg(unix)]
    #[test]
    fn declared_sdk_packages_reject_symlink_escape_and_directory_cycles() {
        for child in [false, true] {
            let fixture = Fixture::new();
            let source = fixture
                .sdk("version: 1\nsdk: dart\npackages:\n  - name: one\n    path: vendor/one\n");
            let outside = fixture.0.join("outside");
            std::fs::create_dir_all(&outside).unwrap();
            std::fs::write(outside.join("secret"), "outside SDK").unwrap();
            std::fs::create_dir_all(source.join("vendor")).unwrap();
            if child {
                fixture.package(&source, "vendor/one", "one");
                std::os::unix::fs::symlink(&outside, source.join("vendor/one/escape")).unwrap();
            } else {
                std::os::unix::fs::symlink(&outside, source.join("vendor/one")).unwrap();
            }
            assert!(
                copy_sdk_packages(&source, &fixture.0.join("packed"))
                    .unwrap_err()
                    .contains("escapes the selected SDK")
            );
        }
        let fixture = Fixture::new();
        let source =
            fixture.sdk("version: 1\nsdk: dart\npackages:\n  - name: one\n    path: vendor/one\n");
        fixture.package(&source, "vendor/one", "one");
        std::os::unix::fs::symlink(source.join("vendor/one"), source.join("vendor/one/cycle"))
            .unwrap();
        assert!(
            copy_sdk_packages(&source, &fixture.0.join("packed"))
                .unwrap_err()
                .contains("cyclic SDK package")
        );
    }
}
