/// The `macro.*` service of `dfexec/1` (docs/BUILD-PROTOCOLO.md §5 and
/// docs/MACROS-PROTOCOLO.md §5), on the executor side: receives requests
/// from the host, instantiates macros through the *bootstrap*'s map, runs the
/// phases and returns the results; during an execution, the macro's queries
/// go to the host as `macro.query`.
///
/// It does not depend on `dart:io`: the transport is a [Channel]. The native
/// executor and the materialization builder (docs/MACROS-COMPATIBILIDADE.md)
/// use the stdio channel (`stdio_channel.dart`); tests, an in-memory channel.
library;

import 'dart:async';

import '../api.dart';
import 'execute.dart';
import 'model.dart';
import 'result.dart';

/// Protocol name and version (the handshake rejects any other).
const protocol = 'dfexec/1';

/// Version of the macro executor (the package's).
const executorVersion = 'dartforge-macros/0.1.3-main.0';

/// A macro factory generated by the bootstrap: the constructor *tear-off*
/// with the annotation's arguments.
typedef MacroFactory = Macro Function(List<Object?> positional, Map<String, Object?> named);

/// Already framed JSON messages (the framing belongs to the channel).
abstract interface class Channel {
  Stream<Map<String, Object?>> get input;
  void send(Map<String, Object?> message);
  Future<void> close();
}

/// Serves the host until `end`. [macros] is the bootstrap's map:
/// `'uri#Class'` → constructor (`''` for the unnamed one) → factory.
Future<void> serve(Map<String, Map<String, MacroFactory>> macros, Channel channel, {String abi = ''}) async {
  final service = _Service(macros, channel, abi);
  await for (final m in channel.input) {
    if (!service.receive(m)) break;
  }
  await Future.wait(service.inProgress);
  await channel.close();
}

final class _Service {
  final Map<String, Map<String, MacroFactory>> macros;
  final Channel channel;
  final String abi;
  final instances = <int, Macro>{};
  final _queries = <int, Completer<Object?>>{};
  final inProgress = <Future<void>>[];
  var _nextInstance = 1;
  var _nextQuery = 1;
  _Service(this.macros, this.channel, this.abi);

  void _error(Object? id, String message) => channel.send({'t': 'error', 'id': id, 'message': message});

  /// Handles a message; `false` ends the session.
  bool receive(Map<String, Object?> m) {
    final id = m['id'];
    switch (m['t']) {
      case 'hello':
        if (m['protocol'] != protocol) {
          _error(null, 'protocol ${m['protocol']} not supported (this executor speaks $protocol)');
          return false;
        }
        channel.send({
          't': 'hello',
          'protocol': protocol,
          'services': ['macro'],
          'executor': executorVersion,
          'abi': abi,
          'macros': [
            for (final MapEntry(:key, :value) in macros.entries)
              {'macro': key, 'constructors': value.keys.toList()},
          ],
        });
      case 'macro.instantiate':
        try {
          final factory = macros[m['macro']]?[m['constructor'] ?? ''];
          if (factory == null) {
            _error(id, 'macro ${m['macro']} (constructor "${m['constructor']}") is not in the bootstrap');
            return true;
          }
          final args = m['arguments'] as Map<String, Object?>? ?? const {};
          final model = Model(_NoHost());
          final macro = factory(
            [for (final a in args['positional'] as List? ?? const []) argumentFromJson(a, model)],
            {
              for (final MapEntry(:key, :value) in (args['named'] as Map<String, Object?>? ?? const {}).entries)
                key: argumentFromJson(value, model),
            },
          );
          final n = _nextInstance++;
          instances[n] = macro;
          channel.send({'t': 'macro.instance', 'id': id, 'instance': n, 'interfaces': interfacesOf(macro)});
        } catch (e) {
          _error(id, 'failed to instantiate ${m['macro']}: $e');
        }
      case 'macro.execute':
        inProgress.add(_execute(m));
      case 'macro.response':
        final c = _queries.remove(id);
        final error = m['error'] as Map<String, Object?>?;
        if (c == null) break;
        if (error != null) {
          c.completeError(HostError(error['kind'] as String? ?? 'unexpected', error['message'] as String? ?? ''));
        } else {
          c.complete(m['value']);
        }
      case 'macro.discard':
        instances.remove(m['instance']);
      case 'end':
        channel.send({'t': 'end'});
        return false;
      default:
        _error(id, 'unknown message: ${m['t']}');
    }
    return true;
  }

  Future<void> _execute(Map<String, Object?> m) async {
    final id = m['id'];
    final macro = instances[m['instance']];
    if (macro == null) {
      _error(id, 'instance ${m['instance']} does not exist');
      return;
    }
    final phase = Phase.values.byName(m['phase'] as String);
    final model = Model(_ThroughChannel(this, id as int));
    model.receive(m['model'] as Map<String, Object?>? ?? const {});
    final targetJson = m['target'] as Map<String, Object?>;
    final Object target = targetJson['k'] == 'library' ? model.library(targetJson) : model.declaration(targetJson);
    final r = await executePhase(macro, phase, target, Introspector(model));
    channel.send({'t': 'macro.result', 'id': id, 'result': r.toJson()});
  }

  Future<Object?> query(int execution, String kind, Map<String, Object?> args) {
    final n = _nextQuery++;
    final c = Completer<Object?>();
    _queries[n] = c;
    channel.send({'t': 'macro.query', 'id': n, 'execution': execution, 'kind': kind, 'args': args});
    return c.future;
  }
}

final class _ThroughChannel implements Host {
  final _Service service;
  final int execution;
  _ThroughChannel(this.service, this.execution);

  @override
  Future<Object?> query(String kind, Map<String, Object?> args) => service.query(execution, kind, args);
}

/// Instantiating queries nothing: arguments are only literals, `Code` and
/// types.
final class _NoHost implements Host {
  @override
  Future<Object?> query(String kind, Map<String, Object?> args) =>
      Future.error(HostError('implementation', 'query outside an execution'));
}

/// An application argument (spec, "Macro arguments"): literal, list, set,
/// map, `Code` or type annotation, tagged with its kind.
Object? argumentFromJson(Object? j, Model m) {
  final a = j as Map<String, Object?>;
  final v = a['v'];
  return switch (a['t']) {
    'null' => null,
    'bool' => v as bool,
    'int' => int.parse(v as String),
    'double' => (v as num).toDouble(),
    'string' => v as String,
    'list' => [for (final x in v as List) argumentFromJson(x, m)],
    'set' => {for (final x in v as List) argumentFromJson(x, m)},
    'map' => {
        for (final pair in v as List) argumentFromJson((pair as List)[0], m): argumentFromJson(pair[1], m),
      },
    'code' => codeFromJson(v, m),
    'type' => m.type(v as Map<String, Object?>).code,
    final t => throw UnexpectedException('unknown argument: $t'),
  };
}

/// The macro interfaces [m] implements, by name: with them the host decides
/// which phases the application runs in (the 1st generation's
/// `shouldExecute`).
List<String> interfacesOf(Macro m) => [
      if (m is LibraryTypesMacro) 'LibraryTypesMacro',
      if (m is LibraryDeclarationsMacro) 'LibraryDeclarationsMacro',
      if (m is LibraryDefinitionMacro) 'LibraryDefinitionMacro',
      if (m is FunctionTypesMacro) 'FunctionTypesMacro',
      if (m is FunctionDeclarationsMacro) 'FunctionDeclarationsMacro',
      if (m is FunctionDefinitionMacro) 'FunctionDefinitionMacro',
      if (m is VariableTypesMacro) 'VariableTypesMacro',
      if (m is VariableDeclarationsMacro) 'VariableDeclarationsMacro',
      if (m is VariableDefinitionMacro) 'VariableDefinitionMacro',
      if (m is ClassTypesMacro) 'ClassTypesMacro',
      if (m is ClassDeclarationsMacro) 'ClassDeclarationsMacro',
      if (m is ClassDefinitionMacro) 'ClassDefinitionMacro',
      if (m is EnumTypesMacro) 'EnumTypesMacro',
      if (m is EnumDeclarationsMacro) 'EnumDeclarationsMacro',
      if (m is EnumDefinitionMacro) 'EnumDefinitionMacro',
      if (m is EnumValueTypesMacro) 'EnumValueTypesMacro',
      if (m is EnumValueDeclarationsMacro) 'EnumValueDeclarationsMacro',
      if (m is EnumValueDefinitionMacro) 'EnumValueDefinitionMacro',
      if (m is FieldTypesMacro) 'FieldTypesMacro',
      if (m is FieldDeclarationsMacro) 'FieldDeclarationsMacro',
      if (m is FieldDefinitionMacro) 'FieldDefinitionMacro',
      if (m is MethodTypesMacro) 'MethodTypesMacro',
      if (m is MethodDeclarationsMacro) 'MethodDeclarationsMacro',
      if (m is MethodDefinitionMacro) 'MethodDefinitionMacro',
      if (m is ConstructorTypesMacro) 'ConstructorTypesMacro',
      if (m is ConstructorDeclarationsMacro) 'ConstructorDeclarationsMacro',
      if (m is ConstructorDefinitionMacro) 'ConstructorDefinitionMacro',
      if (m is MixinTypesMacro) 'MixinTypesMacro',
      if (m is MixinDeclarationsMacro) 'MixinDeclarationsMacro',
      if (m is MixinDefinitionMacro) 'MixinDefinitionMacro',
      if (m is ExtensionTypesMacro) 'ExtensionTypesMacro',
      if (m is ExtensionDeclarationsMacro) 'ExtensionDeclarationsMacro',
      if (m is ExtensionDefinitionMacro) 'ExtensionDefinitionMacro',
      if (m is ExtensionTypeTypesMacro) 'ExtensionTypeTypesMacro',
      if (m is ExtensionTypeDeclarationsMacro) 'ExtensionTypeDeclarationsMacro',
      if (m is ExtensionTypeDefinitionMacro) 'ExtensionTypeDefinitionMacro',
      if (m is TypeAliasTypesMacro) 'TypeAliasTypesMacro',
      if (m is TypeAliasDeclarationsMacro) 'TypeAliasDeclarationsMacro',
    ];
